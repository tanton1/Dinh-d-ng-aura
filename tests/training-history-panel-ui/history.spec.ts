import { expect, test, type Page } from '@playwright/test'
const counts = (page: Page) => page.evaluate(() => ({ history: (window as any).historyCalls.length, usage: (window as any).usageCalls.length }))
const open = async (page: Page, hold = false) => {
  await page.addInitScript((value) => { (window as any).holdHistory = value }, hold)
  await page.goto('/tests/training-history-panel-ui/index.html')
  await expect.poll(() => counts(page)).toEqual({ history: 1, usage: 0 })
}
const resolve = (page: Page, index: number, labels: string[], more = false) => page.evaluate(({ index, labels, more }) => (window as any).historyResolvers[index](labels, more), { index, labels, more })

test('filters and history do not read contract usage; explicit detail reuses its result until refresh', async ({ page }) => {
  await open(page)
  await page.getByRole('button', { name: 'Bộ lọc', exact: true }).click()
  await page.getByRole('tab', { name: 'Lịch sử', exact: true }).click()
  await expect.poll(() => counts(page)).toEqual({ history: 2, usage: 0 })
  await page.getByRole('button', { name: 'Đối chiếu gói tập', exact: true }).click()
  await expect(page.getByText('Gói student-a', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Ẩn đối chiếu gói tập', exact: true }).click()
  await page.getByRole('button', { name: 'Đối chiếu gói tập', exact: true }).click()
  await expect.poll(() => counts(page)).toEqual({ history: 2, usage: 1 })
  await page.getByRole('button', { name: 'Làm mới lịch sử' }).click()
  await expect.poll(() => counts(page)).toEqual({ history: 3, usage: 2 })
})

test('changing the person and range discards delayed responses and hides previous records', async ({ page }) => {
  await open(page, true)
  await page.getByRole('button', { name: 'student-b', exact: true }).click()
  await expect.poll(() => counts(page)).toEqual({ history: 2, usage: 0 })
  await resolve(page, 1, ['current-student'])
  await resolve(page, 0, ['stale-student'])
  await expect(page.locator('.training-history__record')).toContainText('current-student')
  await expect(page.getByText('stale-student', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '90 ngày', exact: true }).click()
  await expect.poll(() => counts(page)).toEqual({ history: 3, usage: 0 })
  await expect(page.getByText('current-student', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '30 ngày', exact: true }).click()
  await expect.poll(() => counts(page)).toEqual({ history: 4, usage: 0 })
  await resolve(page, 3, ['current-range'])
  await resolve(page, 2, ['stale-range'])
  await expect(page.locator('.training-history__record')).toContainText('current-range')
  await expect(page.getByText('stale-range', { exact: true })).toHaveCount(0)
})

test('load more avoids duplicate rows, and selecting PT loads only the PT endpoint', async ({ page }) => {
  await open(page, true)
  await resolve(page, 0, ['record-one'], true)
  await page.getByRole('button', { name: 'Tải thêm lịch sử', exact: true }).click()
  await expect.poll(() => counts(page)).toEqual({ history: 2, usage: 0 })
  await resolve(page, 1, ['record-one', 'record-two'])
  await expect(page.locator('.training-history__record')).toHaveCount(2)
  await page.getByRole('button', { name: 'trainer-1', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).historyCalls.map((call: any) => call.subject))).toEqual(['student', 'student', 'trainer'])
  await resolve(page, 2, ['learner-one', 'learner-two'])
  await expect(page.locator('.training-history__shift')).toHaveCount(1)
  await expect(page.locator('.training-history__shift')).toContainText('2 học viên')
  await expect(page.getByRole('button', { name: 'Đối chiếu gói tập', exact: true })).toHaveCount(0)
})

test('saving a correction refreshes visible history and contract reconciliation', async ({ page }) => {
  await open(page)
  await expect.poll(() => page.evaluate(() => (window as any).activeTrainerDirectoryReads)).toBe(0)
  await page.getByRole('button', { name: 'Đối chiếu gói tập', exact: true }).click()
  await expect(page.getByText('Gói student-a', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Điều chỉnh', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).activeTrainerDirectoryReads)).toBe(1)
  await page.getByPlaceholder('Ví dụ: PT thực dạy khác với lịch ban đầu; đối soát theo camera và xác nhận quản lý.').fill('Đối soát ca dạy kiểm thử')
  await page.getByRole('button', { name: 'Xác nhận điều chỉnh', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => (window as any).activeTrainerDirectoryReads)).toBe(0)
  await expect.poll(() => counts(page)).toEqual({ history: 2, usage: 2 })
  await expect.poll(() => page.evaluate(() => (window as any).correctionCalls.length)).toBe(1)
})

test('a pending correction does not reload a person after leaving their panel', async ({ page }) => {
  await page.addInitScript(() => { (window as any).holdCorrection = true })
  await open(page)
  await page.getByRole('button', { name: 'Điều chỉnh', exact: true }).click()
  await page.getByPlaceholder('Ví dụ: PT thực dạy khác với lịch ban đầu; đối soát theo camera và xác nhận quản lý.').fill('Đối soát ca đang chờ')
  await page.getByRole('button', { name: 'Xác nhận điều chỉnh', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).correctionCalls.length)).toBe(1)
  // A parent route/selection change may unmount the panel while its save is
  // pending, independently of the disabled controls inside the modal.
  await page.getByRole('button', { name: 'student-b', exact: true }).evaluate((button) => button.click())
  await expect.poll(() => counts(page)).toEqual({ history: 2, usage: 0 })
  await page.evaluate(async () => {
    ;(window as any).finishCorrection()
    await new Promise(requestAnimationFrame)
  })
  await expect(page.locator('.training-history__record')).toContainText('student-b')
  expect(await counts(page)).toEqual({ history: 2, usage: 0 })
})
