test('failed and incomplete forced reads remain unknown and retry with refresh true without automatic loops', async ({ page }) => {
  await page.goto(fixture)
  await settled(page)
  await page.evaluate(() => { window.__academy.hold = true; window.__academy.refresh() })
  await count(page, 2)
  await page.evaluate(() => window.__academy.fail(1))
  await expect(page.getByRole('status')).toContainText('Chưa tải được')
  expect((await snapshot(page)).analytics).toEqual([])
  expect((await snapshot(page)).asOf).toBeNull()
  await expect(page.getByRole('article').filter({ hasText: 'HỌC VIÊN GHI DANH' }).locator('strong')).toHaveText('—')
  await expect(page.getByRole('article').filter({ hasText: 'HOÀN THÀNH TRUNG BÌNH' }).locator('strong')).toHaveText('—')
  await expect(page.getByRole('progressbar')).toHaveCount(0)
  await page.evaluate(() => { window.__academy.visibility('hidden'); window.__academy.visibility('visible'); window.dispatchEvent(new Event('online')) })
  await idle(page)
  await count(page, 2)
  await page.getByRole('button', { name: 'Toggle route' }).click()
  await page.getByRole('button', { name: 'Toggle route' }).click()
  await count(page, 3)
  expect(await page.evaluate(() => window.__academy.calls[2].refresh)).toBe(true)
  await page.evaluate(() => window.__academy.settle(2, 99, false))
  await expect(page.getByRole('status')).toContainText('Chưa đủ dữ liệu')
  expect((await snapshot(page)).analytics).toEqual([])
  await page.getByRole('button', { name: 'Làm mới số liệu', exact: true }).click()
  await count(page, 4)
  expect(await page.evaluate(() => window.__academy.calls[3].refresh)).toBe(true)
  await page.evaluate(() => window.__academy.settle(3, 10))
  await settled(page, 10)
})

for (const boundary of ['Change account', 'Change authority', 'Replace session']) {
for (const outcome of ['success', 'failure'] as const) test(`late ${outcome} after ${boundary} and old mutation callback cannot publish or invalidate the new scope`, async ({ page }) => {
  await page.goto(`${fixture}?hold`)
  await count(page, 1)
  const oldSubscription = await page.evaluate(() => window.__academy.subscriptions.findIndex(item => item.active))
  expect(oldSubscription).toBeGreaterThanOrEqual(0)
  await page.getByRole('button', { name: boundary, exact: true }).click()
  await count(page, 2)
  expect((await snapshot(page)).analytics).toEqual([])
  await page.evaluate(() => window.__academy.settle(1, 21))
  await settled(page, 21)
  await page.evaluate(({ outcome, oldSubscription }) => {
    if (outcome === 'success') window.__academy.settle(0, 99)
    else window.__academy.fail(0)
    window.__academy.oldInvalidate()
    // Deliberately violate transport unsubscribe to test client fencing as well.
    window.__academy.subscriptions[oldSubscription].success([])
    window.__academy.subscriptions[oldSubscription].error(new Error('old catalog failure'))
  }, { outcome, oldSubscription })
  await idle(page)
  await settled(page, 21)
  expect((await snapshot(page)).catalogError).toBeNull()
  await count(page, 2)
})
}

