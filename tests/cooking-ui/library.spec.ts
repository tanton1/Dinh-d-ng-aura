import { expect, test } from '@playwright/test'

for (const width of [320, 390, 768, 1440]) {
  test(`existing menu has compact touch actions and three tabs at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 })
    await page.goto('/tests/cooking-ui/index.html#/food-library')
    const cards = page.locator('.meal-plan-live-card')
    await expect(cards).toHaveCount(7)
    await expect(page.getByRole('heading', { name: 'Tra Cứu Kcal Món Ăn', exact: true })).toBeVisible()
    if (width <= 390) await page.screenshot({ path: `test-results/kcal-lookup-${width}.png` })
    expect(await page.getByRole('tablist', { name: 'Nội dung tra cứu' }).getByRole('tab').allTextContents()).toEqual(['Món ăn', 'Nguyên liệu', 'Kế hoạch 7 ngày'])
    await expect(page.getByRole('button', { name: /Ghi nhật ký/ })).toHaveCount(0)
    await expect(page.getByRole('group', { name: 'Lọc nhanh thực đơn' })).toHaveCount(0)
    await expect(page.getByText('Trang nguồn không nêu rõ khẩu phần chuẩn')).toHaveCount(0)
    const tabBounds = await page.getByRole('tab', { name: 'Món ăn', exact: true }).boundingBox()
    expect(tabBounds!.height).toBeGreaterThanOrEqual(44)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('button', { name: 'Lưu Ức gà áp chảo & rau củ', exact: true }).click()
    await page.getByRole('button', { name: 'Xem món đã lưu', exact: true }).click()
    await expect(cards).toHaveCount(1)
    await page.getByRole('button', { name: 'Hiện tất cả', exact: true }).click()
    await page.getByRole('tab', { name: 'Nguyên liệu', exact: true }).click()
    await expect(cards).toHaveCount(4)
    const artwork = page.getByRole('img', { name: 'Ảnh minh hoạ Bơ', exact: true })
    await artwork.scrollIntoViewIfNeeded()
    await expect.poll(() => artwork.locator('img').evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0)).toBe(true)
    await page.getByRole('searchbox', { name: 'Tìm nguyên liệu' }).fill('com trang')
    await expect(cards).toHaveCount(1)
    await expect(cards.first()).toContainText('Cơm trắng')
    await page.getByRole('button', { name: 'Bộ lọc', exact: true }).click()
    await expect(page.getByRole('combobox', { name: 'Nhóm nguyên liệu', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}

test('dish and ingredient filters retain independent values and units on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/tests/cooking-ui/index.html#/food-library')
  const cards = page.locator('.meal-plan-live-card')
  await expect(cards).toHaveCount(7)
  await page.getByRole('button', { name: 'Bộ lọc', exact: true }).click()
  await page.getByRole('combobox', { name: 'Nhóm món', exact: true }).selectOption('Món chính')
  await page.getByRole('combobox', { name: 'Kcal theo nguồn', exact: true }).selectOption('higher')
  await expect(cards).toHaveCount(1)
  await expect(cards.first()).toContainText('Cá hồi áp chảo & măng tây')
  await expect(page.getByRole('combobox', { name: 'Đạm trên 100 g' })).toHaveCount(0)
  await page.getByRole('tab', { name: 'Nguyên liệu', exact: true }).click()
  await expect(cards).toHaveCount(4)
  await expect(page.getByRole('combobox', { name: 'Nhóm nguyên liệu', exact: true })).toHaveValue('all')
  await page.getByRole('combobox', { name: 'Năng lượng trên 100 g', exact: true }).selectOption('lower')
  await expect(cards).toHaveCount(1)
  await expect(cards.first()).toContainText('Khoai lang luộc')
  await page.getByRole('combobox', { name: 'Năng lượng trên 100 g', exact: true }).selectOption('all')
  await page.getByRole('combobox', { name: 'Đạm trên 100 g', exact: true }).selectOption('at-least-20')
  await expect(cards).toHaveCount(2)
  await page.getByRole('searchbox', { name: 'Tìm nguyên liệu', exact: true }).fill('ca hoi')
  await expect(cards).toHaveCount(1)
  await page.screenshot({ path: 'test-results/kcal-ingredient-filters-390.png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('tab', { name: 'Món ăn', exact: true }).click()
  await expect(page.getByRole('searchbox', { name: 'Tìm món ăn', exact: true })).toHaveValue('')
  await expect(page.getByRole('combobox', { name: 'Nhóm món', exact: true })).toHaveValue('Món chính')
  await expect(page.getByRole('combobox', { name: 'Kcal theo nguồn', exact: true })).toHaveValue('higher')
  await expect(cards).toHaveCount(1)
  await page.getByRole('tab', { name: 'Nguyên liệu', exact: true }).click()
  await expect(page.getByRole('searchbox', { name: 'Tìm nguyên liệu', exact: true })).toHaveValue('ca hoi')
  await expect(page.getByRole('combobox', { name: 'Đạm trên 100 g', exact: true })).toHaveValue('at-least-20')
  await expect(cards).toHaveCount(1)
  await page.getByRole('button', { name: 'Xóa lọc', exact: true }).click()
  await expect(page.getByRole('searchbox', { name: 'Tìm nguyên liệu', exact: true })).toHaveValue('ca hoi')
  await expect(page.getByRole('combobox', { name: 'Đạm trên 100 g', exact: true })).toHaveValue('all')
})

test('ingredient atlases load near the viewport and do not preload the whole collection', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const requested = new Set<string>()
  page.on('request', request => { if (request.url().includes('/images/ingredients/atlas-')) requested.add(request.url()) })
  await page.goto('/tests/cooking-ui/index.html?artwork=1#/food-library?tab=ingredients')
  await page.getByRole('tab', { name: 'Nguyên liệu', exact: true }).click()
  const art = page.locator('.ingredient-artwork')
  await expect(art).toHaveCount(17)
  await expect.poll(() => requested.size).toBeGreaterThan(0)
  expect(requested.size).toBeLessThan(17)
  await expect(art.last().locator('img')).toHaveCount(0)
  await art.last().scrollIntoViewIfNeeded()
  await expect.poll(() => art.last().locator('img').evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true)
  await art.last().locator('img').evaluate((image: HTMLImageElement) => image.decode())
  const crop = await art.last().locator('.ingredient-artwork__crop').boundingBox()
  expect(crop!.width).toBeGreaterThan(80)
  expect(crop!.height).toBeGreaterThan(80)
  expect([...requested].some(url => url.endsWith('atlas-16.webp'))).toBe(true)
  await page.screenshot({ path: 'test-results/ingredient-artwork-mobile.png', fullPage: false })
})
