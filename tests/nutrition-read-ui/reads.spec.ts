test('pending forced summary polls and manual retries retain the server freshness boundary', async ({ page }) => {
  await page.goto(`${path}#/nutrition?section=diary`)
  await page.getByRole('tab', { name: 'Tháng', exact: true }).click()
  await expect(page.getByText('TỔNG NĂNG LƯỢNG TRONG KỲ')).toBeVisible()
  await page.evaluate(() => (window as any).nutritionFixture.hold = ['summary'])
  await page.getByRole('button', { name: 'Làm mới nhật ký', exact: true }).click()
  await expect.poll(async () => (await calls(page, 'summary')).length).toBe(2)
  const forced = (await calls(page, 'summary'))[1]
  const refreshAfter = '2026-10-24T04:30:00.000Z'
  expect(forced.input.forceRefresh).toBe(true)
  await page.evaluate(({ id, input, refreshAfter }) => (window as any).nutritionFixture.release(id, { ...input, coverage: 'pending', items: [], retryAfterMs: 500, refreshAfter }), { ...forced, refreshAfter })
  await expect.poll(async () => (await calls(page, 'summary')).length).toBe(3)
  const poll = (await calls(page, 'summary'))[2]
  expect(poll.input.forceRefresh).toBe(false)
  expect(poll.input.refreshAfter).toBe(refreshAfter)
  await expect(page.getByText('TỔNG NĂNG LƯỢNG TRONG KỲ')).toHaveCount(0)
  await page.evaluate(({ id, input, refreshAfter }) => (window as any).nutritionFixture.release(id, { ...input, coverage: 'pending', items: [], retryAfterMs: 500, refreshAfter }), { ...poll, refreshAfter })
  await expect.poll(async () => (await calls(page, 'summary')).length).toBe(4)
  const lastPoll = (await calls(page, 'summary'))[3]
  await page.evaluate(({ id, input, refreshAfter }) => (window as any).nutritionFixture.release(id, { ...input, coverage: 'pending', items: [], refreshAfter }), { ...lastPoll, refreshAfter })
  await page.getByRole('button', { name: 'Làm mới nhật ký', exact: true }).click()
  await expect.poll(async () => (await calls(page, 'summary')).length).toBe(5)
  const resumed = (await calls(page, 'summary'))[4]
  expect(resumed.input.forceRefresh).toBe(false)
  expect(resumed.input.refreshAfter).toBe(refreshAfter)
  await page.evaluate((id: number) => (window as any).nutritionFixture.release(id), resumed.id)
  await expect(page.getByText('TỔNG NĂNG LƯỢNG TRONG KỲ')).toBeVisible()
  expect(await calls(page, 'history-meals')).toHaveLength(0)
  await page.getByRole('button', { name: 'Làm mới nhật ký', exact: true }).click()
  await expect.poll(async () => (await calls(page, 'summary')).length).toBe(6)
  const fresh = (await calls(page, 'summary'))[5]
  expect(fresh.input.forceRefresh).toBe(true)
  expect(fresh.input.refreshAfter).toBeUndefined()
  await page.evaluate((id: number) => (window as any).nutritionFixture.release(id), fresh.id)
})

