test('plan mutations from an earlier A-B-A visit cannot replace newer state or clear its saving flag', async ({ page }) => {
  await page.goto(`${path}?mode=library#/food-library`)
  await page.getByRole('tab', { name: 'Kế hoạch 7 ngày', exact: true }).click()
  await page.evaluate(() => (window as any).nutritionFixture.hold = ['generate-plan'])
  const generate = page.getByRole('button', { name: 'Tạo kế hoạch 7 ngày', exact: true })
  await generate.click()
  await expect.poll(async () => (await calls(page, 'generate-plan')).length).toBe(1)
  await page.getByRole('button', { name: 'Tuần sau', exact: true }).click()
  await page.getByRole('button', { name: 'Tuần trước', exact: true }).click()
  await generate.click()
  await expect.poll(async () => (await calls(page, 'generate-plan')).length).toBe(2)
  const requests = await calls(page, 'generate-plan')
  expect(requests[0].input.weekStart).toBe(requests[1].input.weekStart)
  const plan = (revision: number) => ({ schemaVersion: 1, weekStart: requests[0].input.weekStart, revision, status: 'draft', source: 'aura-catalog', sourceTitle: `Plan revision ${revision}`, targets: {}, days: [], updatedAt: null })
  await page.evaluate(({ id, plan }) => (window as any).nutritionFixture.release(id, plan), { id: requests[1].id, plan: plan(3) })
  await expect(page.getByText('Plan revision 3', { exact: true })).toBeVisible()
  await generate.click()
  await expect.poll(async () => (await calls(page, 'generate-plan')).length).toBe(3)
  await page.evaluate(({ id, plan }) => (window as any).nutritionFixture.release(id, plan), { id: requests[0].id, plan: plan(2) })
  await expect(page.getByText('Plan revision 3', { exact: true })).toBeVisible()
  await expect(page.getByText('Plan revision 2', { exact: true })).toHaveCount(0)
  await expect(generate).toBeDisabled()
  const current = (await calls(page, 'generate-plan'))[2]
  await page.evaluate(({ id, plan }) => (window as any).nutritionFixture.release(id, plan), { id: current.id, plan: plan(4) })
  await expect(page.getByText('Plan revision 4', { exact: true })).toBeVisible()
  await expect(generate).toBeEnabled()
})

