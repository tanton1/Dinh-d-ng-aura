import { expect, test } from '@playwright/test'

for (const v4 of [false, true]) {
  test(`standalone food library saves a chosen portion and keeps its own deep link (UI v4=${v4})`, async ({ page }) => {
    const errors: string[] = []
    const remoteWrites: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.route(/firestore\.googleapis\.com|cloudfunctions\.net|\.run\.app\//, (route) => {
      remoteWrites.push(route.request().url())
      return route.abort()
    })
    await page.addInitScript((enabled) => localStorage.setItem('aura:ui-rollout:demo-config:v1', JSON.stringify({ schemaVersion: 1, surfaces: { shell: enabled ? 'all' : 'off', 'member-nutrition': enabled ? 'all' : 'off' } })), v4)
    await page.goto('/#/food-library')
    await expect(page.getByRole('heading', { name: 'Thư viện món ăn', exact: true })).toBeVisible()
    await expect(page.getByRole('navigation', { name: 'Điều hướng dinh dưỡng' })).toHaveCount(0)
    await expect(page.locator('.food-library__card')).toHaveCount(6)
    await page.getByRole('button', { name: 'Lưu Cơm trắng', exact: true }).click()
    await page.getByRole('button', { name: 'Đã lưu', exact: true }).click()
    await expect(page.locator('.food-library__card')).toHaveCount(1)
    await page.getByLabel('Chỉnh khẩu phần Cơm trắng', { exact: true }).click()
    await page.getByRole('button', { name: '0,5×', exact: true }).click()
    await page.getByRole('button', { name: 'Ghi nhật ký: Cơm trắng', exact: true }).click()
    const editor = page.getByRole('dialog', { name: 'Kiểm tra bữa ăn' })
    await expect(editor).toContainText('65 kcal')
    await editor.getByRole('combobox').selectOption('snack')
    await editor.getByRole('button', { name: 'Ghi nhật ký', exact: true }).click()
    await expect(editor).toHaveCount(0)
    await expect(page.locator('.nutrition-toast')).toContainText('Đã thêm Cơm trắng')
    const savedMeal = await page.evaluate(() => JSON.parse(localStorage.getItem('aura:nutrition:meals:v2:demo-admin') ?? '[]').find((meal: { catalogId?: string }) => meal.catalogId === 'demo-com-trang'))
    expect(savedMeal.calories).toBe(65)
    expect(savedMeal.servingMultiplier).toBe(0.5)
    await expect(page).toHaveURL(/#\/food-library$/)
    await page.getByRole('button', { name: 'Xem nhật ký', exact: true }).click()
    await expect(page).toHaveURL(/#\/nutrition\?section=diary$/)
    await expect(page.getByTestId('nutrition-dashboard')).toContainText('Cơm trắng')
    await page.goto('/#/food-library?saved=1')
    await expect(page.locator('.food-library__card')).toHaveCount(1)
    await page.getByRole('button', { name: 'Xem chi tiết Cơm trắng', exact: true }).click()
    await expect(page).toHaveURL(/#\/food-library\?foodId=demo-com-trang$/)
    await page.getByRole('button', { name: 'Quay lại thư viện món ăn', exact: true }).click()
    await expect(page.locator('.food-library__card')).toHaveCount(1)
    await page.getByRole('button', { name: 'Xem chi tiết Cơm trắng', exact: true }).click()
    await page.reload()
    await expect(page.locator('#nutrition-food-title')).toHaveText('Cơm trắng')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(remoteWrites).toEqual([])
    expect(errors).toEqual([])
  })
}
