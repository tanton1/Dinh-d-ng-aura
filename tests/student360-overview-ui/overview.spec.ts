test('same-scope latest refresh owns success, denial and refreshing state', async ({ page }) => {
  await resolve(page, 0)
  await name(page, 'Learner A')
  await page.getByRole('button', { name: 'Hợp đồng', exact: true }).first().click()
  const refresh = page.getByRole('button', { name: 'Fixture contract saved for A' })
  await refresh.click()
  await pending(page, 2)
  await refresh.click()
  await pending(page, 3)
  await page.evaluate(() => (window as any).student360.reject(1))
  await settle(page)
  await page.getByLabel('Mở menu nghiệp vụ').click()
  await expect(page.getByRole('button', { name: 'Đối soát dữ liệu' })).toBeDisabled()
  await name(page, 'Learner A')
  await resolve(page, 2, 'Latest summary')
  await name(page, 'Latest summary')
  await expect(page.getByRole('button', { name: 'Đối soát dữ liệu' })).toBeEnabled()
  await page.getByLabel('Mở menu nghiệp vụ').click()
  await refresh.click()
  await pending(page, 4)
  await refresh.click()
  await pending(page, 5)
  await resolve(page, 4, 'Newest summary')
  await name(page, 'Newest summary')
  await resolve(page, 3, 'Stale summary')
  await settle(page)
  await name(page, 'Newest summary')
})

test('retired forced projection and mutation callback do not issue followup reads', async ({ page }) => {
  await resolve(page, 0)
  await name(page, 'Learner A')
  await page.getByRole('button', { name: 'Hợp đồng', exact: true }).first().click()
  await expect(page.getByRole('button', { name: 'Fixture contract saved for A' })).toBeVisible()
  await page.getByLabel('Mở menu nghiệp vụ').click()
  await page.getByRole('button', { name: 'Đối soát dữ liệu' }).click()
  await pending(page, 2)
  await page.evaluate(() => (window as any).student360.go('B'))
  await pending(page, 3)
  await resolve(page, 2)
  await name(page, 'Learner B')
  await resolve(page, 1)
  await page.evaluate(() => (window as any).student360.contractCallbacks[0]())
  await settle(page)
  await pending(page, 3)
  await name(page, 'Learner B')
  await expect(page.getByRole('button', { name: 'Fixture contract saved for A' })).toHaveCount(0)
  expect(await page.evaluate(() => (window as any).student360.pending.map((r: any) => [r.kind, r.studentId]))).toEqual([['overview', 'A'], ['projection', 'A'], ['overview', 'B']])
})

