import { expect, test } from '@playwright/test'

for (const width of [320, 390, 1280]) test(`member tiers and reward editor fit ${width}px`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 844 })
  await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
  await page.goto('/tests/loyalty-operations-ui/admin.html?demo')
  const nav = page.getByRole('navigation', { name: 'Vận hành Aura Club' })
  await nav.getByRole('button', { name: 'Thành viên', exact: true }).click()
  await page.getByRole('tab', { name: /^Gold/ }).click()
  await expect(page.locator('#club-tier-members article')).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  await page.screenshot({ path: info.outputPath('members.png'), fullPage: true })
  await nav.getByRole('button', { name: 'Quà tặng', exact: true }).click()
  await page.getByRole('button', { name: 'Thêm quà', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Thêm quà tặng' })
  await expect(dialog.getByRole('button', { name: 'Lưu quà tặng' })).toBeInViewport()
  await dialog.getByRole('textbox', { name: 'Mô tả', exact: true }).scrollIntoViewIfNeeded()
  await dialog.getByRole('textbox', { name: 'Mô tả', exact: true }).fill('Banner quà tặng Aura')
  await expect(dialog.getByRole('textbox', { name: 'Mô tả', exact: true })).toBeInViewport()
  await expect(dialog.getByRole('button', { name: 'Lưu quà tặng' })).toBeInViewport()
  const editorBounds = await dialog.evaluate(element => {
    const fields = element.querySelector('.club-reward-scroll')!.getBoundingClientRect()
    const footer = element.querySelector('footer')!.getBoundingClientRect()
    return { fieldsBottom: fields.bottom, footerTop: footer.top, width: element.getBoundingClientRect().width }
  })
  expect(editorBounds.fieldsBottom).toBeLessThanOrEqual(editorBounds.footerTop)
  expect(editorBounds.width).toBeLessThanOrEqual(width)
  await page.screenshot({ path: info.outputPath('editor-mobile.png'), fullPage: true })
})

test('reward banners preview, save, reopen and remove without losing reward details', async ({ page }, info) => {
  await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
  await page.goto('/tests/loyalty-operations-ui/admin.html?demo')
  const nav = page.getByRole('navigation', { name: 'Vận hành Aura Club' })
  await nav.getByRole('button', { name: 'Quà tặng', exact: true }).click()
  await page.getByRole('button', { name: 'Sửa', exact: true }).first().click()
  const dialog = page.getByRole('dialog', { name: 'Sửa quà tặng' })
  await dialog.getByLabel('Ảnh banner quà tặng').setInputFiles({ name: 'banner.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg/>') })
  await expect(dialog.getByRole('alert')).toContainText('JPG, PNG hoặc WebP')
  await dialog.getByLabel('Ảnh banner quà tặng').setInputFiles('public/images/aura-club/rewards-gifts-960.webp')
  await expect(dialog.locator('.club-gift-image img')).toHaveAttribute('src', /^blob:/)
  await expect(dialog.getByRole('alert')).toHaveCount(0)
  const name = await dialog.getByLabel('Tên quà', { exact: true }).inputValue()
  await dialog.getByRole('button', { name: 'Lưu quà tặng', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  const gift = page.locator('.loyalty-admin-rewards__grid article').filter({ hasText: name })
  await expect(gift.locator('.club-gift-image img')).toHaveAttribute('src', /^data:image\/webp/)
  await gift.getByRole('button', { name: 'Sửa', exact: true }).click()
  await expect(dialog.getByLabel('Tên quà', { exact: true })).toHaveValue(name)
  await expect(dialog.locator('.club-gift-image img')).toBeVisible()
  await page.screenshot({ path: info.outputPath('reward-banner-editor.png'), fullPage: true })
  await dialog.getByRole('button', { name: 'Bỏ ảnh', exact: true }).click()
  await dialog.getByRole('button', { name: 'Lưu quà tặng', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(gift.locator('.club-gift-image img')).toHaveCount(0)
  await expect(gift.getByRole('heading', { name, exact: true })).toBeVisible()
})

