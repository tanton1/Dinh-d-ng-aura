import { expect, test } from '@playwright/test'
const url = '/tests/training-history-workspace-ui/index.html'

test('request tabs lead and never load the history directory or panel', async ({ page }) => {
  const modules: string[] = []
  page.on('request', (request) => modules.push(request.url()))
  await page.goto(url)
  await expect(page.getByRole('tab').first()).toHaveText('Đổi / Hủy')
  await expect(page.getByRole('tab').nth(1)).toHaveText('OFF / Bảo lưu')
  await expect(page.getByTestId('request-kind')).toHaveText('session')
  await page.getByRole('tab', { name: 'OFF / Bảo lưu' }).click()
  await expect(page.getByTestId('request-kind')).toHaveText('pause')
  await page.getByRole('tab', { name: 'Tất cả yêu cầu' }).click()
  await expect(page.getByTestId('request-kind')).toHaveText('all')
  const calls = await page.evaluate(() => (window as any).historyFixture)
  expect(calls.requests).toEqual(['session', 'pause', 'all'])
  expect(calls.directory).toEqual([])
  expect(calls.histories).toEqual([])
  expect(calls.acquisitions).toBe(0)
  expect(modules.some((module) => module.includes('TrainingHistoryDirectory.tsx'))).toBe(false)
  expect(modules.some((module) => module.includes('/panel.tsx'))).toBe(false)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

test('history is explicit, paginated, searchable by email, and keeps the selected person', async ({ page }) => {
  await page.goto(url)
  await page.getByRole('tab', { name: 'Lịch sử học viên' }).click()
  await expect(page.getByRole('button', { name: 'Học viên An' })).toBeVisible()
  expect(await page.evaluate(() => (window as any).historyFixture.histories)).toEqual([])
  await page.getByRole('button', { name: 'Học viên An' }).click()
  await expect(page.getByTestId('history-person')).toContainText('student:student-1')
  await page.getByRole('button', { name: 'Tải thêm học viên' }).click()
  await expect(page.getByRole('button', { name: 'Học viên Chi' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Học viên An' })).toHaveCount(1)
  await page.getByLabel('Tìm học viên').fill('nguyet@example.com')
  await expect(page.getByRole('button', { name: /Minh Nguyệt/ })).toBeVisible()
  await expect(page.getByTestId('history-person')).toContainText('student:student-1')
  const calls = await page.evaluate(() => (window as any).historyFixture)
  expect(calls.directory).toEqual([{ pageSize: 50 }, { pageSize: 50, cursor: 'next-page' }, { query: 'nguyet@example.com', pageSize: 50 }])
  expect(calls.histories).toHaveLength(1)
  expect(calls.acquisitions).toBe(0)
})

test('a late search cannot replace a newer result or fetch an unrelated history', async ({ page }) => {
  await page.goto(url)
  await page.getByRole('tab', { name: 'Lịch sử học viên' }).click()
  await page.getByLabel('Tìm học viên').fill('chậm')
  await expect.poll(() => page.evaluate(() => typeof (window as any).historyFixture.releaseSlow)).toBe('function')
  await page.getByLabel('Tìm học viên').fill('nguyet@example.com')
  await expect(page.getByRole('button', { name: /Minh Nguyệt/ })).toBeVisible()
  await page.evaluate(() => (window as any).historyFixture.releaseSlow())
  await expect(page.getByRole('button', { name: /Minh Nguyệt/ })).toBeVisible()
  await expect(page.getByText('Kết quả cũ')).toHaveCount(0)
  expect(await page.evaluate(() => (window as any).historyFixture.histories)).toEqual([])
})

test('only the PT tab acquires the trainer directory and it releases on OFF', async ({ page }) => {
  await page.goto(url)
  await page.getByRole('tab', { name: 'Lịch dạy PT' }).click()
  await expect(page.getByRole('button', { name: /PT An/ })).toBeVisible()
  expect(await page.evaluate(() => (window as any).historyFixture.histories)).toEqual([])
  await page.getByRole('button', { name: /PT An/ }).click()
  await expect(page.getByTestId('history-person')).toContainText('trainer:trainer-1')
  await page.getByRole('tab', { name: 'OFF / Bảo lưu' }).click()
  await expect(page.getByTestId('request-kind')).toHaveText('pause')
  const calls = await page.evaluate(() => (window as any).historyFixture)
  expect(calls.directory).toEqual([])
  expect(calls.acquisitions).toBe(1)
  expect(calls.releases).toBe(1)
})

test('a direct history link keeps its person even outside the first directory page', async ({ page }) => {
  await page.goto(`${url}#admin-training-history?studentId=student-outside-page&sessionId=focus-session&date=2026-10-21`)
  await expect(page.getByRole('tab', { name: 'Lịch sử học viên' })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('button', { name: 'Học viên An' })).toBeVisible()
  await expect(page.getByTestId('history-person')).toContainText('student:student-outside-page')
  const calls = await page.evaluate(() => (window as any).historyFixture)
  expect(calls.histories).toHaveLength(1)
  expect(calls.histories[0]).toMatchObject({ subjectId: 'student-outside-page', focusSessionId: 'focus-session', focusDate: '2026-10-21' })
  expect(calls.requests).toEqual([])
})

test('changing a history link on the same page selects the new person and focus', async ({ page }) => {
  await page.goto(`${url}#admin-training-history?studentId=student-1`)
  await expect(page.getByTestId('history-person')).toContainText('student:student-1:Học viên An')
  await page.getByLabel('Tìm học viên').fill('nguyet@example.com')
  await expect(page.getByRole('button', { name: /Minh Nguyệt/ })).toBeVisible()
  await expect(page.getByTestId('history-person')).toContainText('student:student-1:Học viên An')
  await page.evaluate(() => { window.location.hash = 'admin-training-history?trainerId=trainer-1&sessionId=new-focus&date=2026-10-23' })
  await expect(page.getByRole('tab', { name: 'Lịch dạy PT' })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByTestId('history-person')).toContainText('trainer:trainer-1:PT An')
  const calls = await page.evaluate(() => (window as any).historyFixture)
  expect(calls.histories.at(-1)).toMatchObject({ subject: 'trainer', subjectId: 'trainer-1', focusSessionId: 'new-focus', focusDate: '2026-10-23' })
})

