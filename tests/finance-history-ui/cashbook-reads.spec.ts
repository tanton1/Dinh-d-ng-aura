test('a late permission error from a closed tab cannot clear the current authorized result', async ({ page }) => {
  await boot(page)
  await page.evaluate(() => { (window as any).financeState.bookDefer = ['receipts'] })
  await page.getByRole('button', { name: 'Phiếu thu', exact: true }).click()
  await expect.poll(() => calls(page)).toHaveLength(3)
  await page.getByRole('button', { name: 'Phiếu chi', exact: true }).click()
  await expect(page.locator('.expense-voucher-list')).toContainText('admin-a:expense')
  await page.evaluate(() => (window as any).financeState.bookPending[0].reject('permission-denied'))
  await selectAccount(page).selectOption('cash-a')
  await expect(page.locator('.expense-voucher-list')).toContainText('admin-a:expense')
  await expect(page.getByRole('alert')).toHaveCount(0)
  expect(await calls(page)).toEqual(['receipts', 's2e', 'receipts', 'vouchers', 'vouchers'])
  expect(await accountCalls(page)).toBe(1)
})

test('old balance reads cannot replace a new owner and loaded account errors do not appear as zero', async ({ page }) => {
  await boot(page)
  await page.evaluate(() => { (window as any).financeState.cashDefer = true })
  await page.getByRole('button', { name: 'Tải lại', exact: true }).click()
  await expect.poll(() => accountCalls(page)).toBe(2)
  await page.evaluate(() => { (window as any).financeState.cashAccounts[0].name = 'New owner fund' })
  await page.getByRole('button', { name: 'Change account', exact: true }).click()
  await expect.poll(() => accountCalls(page)).toBe(3)
  await page.evaluate(() => { const s = (window as any).financeState; s.resolveCash(1); s.resolveCash(0, 'permission-denied') })
  await expect(selectAccount(page).getByRole('option', { name: /New owner fund/ })).toHaveCount(1)
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.evaluate(() => { const s = (window as any).financeState; s.cashDefer = false; s.cashFailure = 'unavailable' })
  await page.getByRole('button', { name: 'Tải lại', exact: true }).click()
  await expect(page.locator('.cashbook-summary')).toContainText('Chưa tải được')
  await expect(page.getByRole('button', { name: 'Lập phiếu thu', exact: true })).toBeDisabled()
})
