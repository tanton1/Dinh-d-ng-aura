import { expect, test, type Page } from '@playwright/test'

const calls = (page: Page) => page.evaluate(() => (window as any).financeState.bookCalls.map((row: any) => row.name))
const accountCalls = (page: Page) => page.evaluate(() => (window as any).financeState.cashCalls.length)
const selectAccount = (page: Page) => page.getByRole('combobox', { name: 'Lọc theo tài khoản quỹ', exact: true })
async function boot(page: Page) {
  await page.goto('/tests/finance-history-ui/index.html?workspace=cashbook')
  await expect(page.locator('.receipt-voucher-list article')).toHaveCount(1)
  await page.getByRole('button', { name: 'Sổ S2e-HKD', exact: true }).click()
  await expect(page.getByRole('article', { name: 'Mẫu S2e-HKD - Sổ chi tiết tiền' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Lập phiếu thu', exact: true })).toBeEnabled()
}

test('opening, changing the period and idling only read the visible book and required accounts', async ({ page }) => {
  await boot(page)
  expect(await calls(page)).toEqual(['receipts', 's2e'])
  expect(await accountCalls(page)).toBe(1)
  await page.getByLabel('Từ ngày', { exact: true }).fill('2026-09-01')
  await expect.poll(() => calls(page)).toEqual(['receipts', 's2e', 's2e'])
  expect(await accountCalls(page)).toBe(1)
  await page.clock.install()
  await page.clock.fastForward(300_000)
  expect(await calls(page)).toEqual(['receipts', 's2e', 's2e'])
  await expect(page.locator('.cashbook-summary')).not.toContainText('phiếu thu')
})

test('each tab reads only its own list and returning performs one fresh read', async ({ page }, testInfo) => {
  await boot(page)
  for (const name of ['Phiếu thu', 'Phiếu chi', 'Biến động quỹ', 'Phiếu thu']) {
    await page.getByRole('button', { name, exact: true }).click()
    await expect(page.getByText('1 chứng từ đã tải.', { exact: false })).toBeVisible()
  }
  expect(await calls(page)).toEqual(['receipts', 's2e', 'receipts', 'vouchers', 'cash', 'receipts'])
  expect(await accountCalls(page)).toBe(1)
  await page.getByRole('button', { name: 'Phiếu thu', exact: true }).click()
  expect(await calls(page)).toHaveLength(6)
  await page.screenshot({ path: `tmp/cashbook-read-validation/${testInfo.project.name}.png`, fullPage: true })
})

test('account filtering ignores older responses even after returning to the same filter', async ({ page }) => {
  await boot(page)
  await page.evaluate(() => { (window as any).financeState.bookDefer = ['receipts'] })
  await page.getByRole('button', { name: 'Phiếu thu', exact: true }).click()
  await expect.poll(() => calls(page)).toHaveLength(3)
  await selectAccount(page).selectOption('cash-a')
  await expect.poll(() => calls(page)).toHaveLength(4)
  await selectAccount(page).selectOption('')
  await expect.poll(() => calls(page)).toHaveLength(5)
  await page.evaluate(() => { const s = (window as any).financeState; s.bookPending[1].resolve(); s.bookPending[0].resolve() })
  await expect(page.locator('.receipt-voucher-list article')).toHaveCount(0)
  await page.evaluate(() => (window as any).financeState.bookPending[2].resolve())
  await expect(page.locator('.receipt-voucher-list')).toContainText('admin-a:all:receipt')
  expect(await accountCalls(page)).toBe(1)
})

