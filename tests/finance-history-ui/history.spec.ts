import { expect, test, type Page } from '@playwright/test'

const count = (page: Page) => page.evaluate(() => (window as any).financeState.calls.length)
const history = (page: Page) => page.getByRole('dialog', { name: 'Sổ giao dịch', exact: true })
async function boot(page: Page) {
  await page.goto('/tests/finance-history-ui/index.html')
  await expect(page.getByRole('heading', { name: 'Công nợ', exact: true })).toBeVisible()
}
async function open(page: Page) { await page.getByRole('button', { name: 'Mở lịch sử thu trả góp', exact: true }).click() }

test('hidden history makes no ledger calls on entry, filters, idle or receivables refresh', async ({ page }) => {
  await boot(page)
  await expect(page.locator('.aura-metric-carousel__slide').first()).toContainText('1.500.000đ')
  await page.getByRole('combobox', { name: 'Lọc chi nhánh công nợ', exact: true }).selectOption('b')
  await page.locator('.date-range-filter__trigger').click()
  await page.getByRole('option', { name: 'Tháng trước', exact: true }).click()
  await page.getByRole('button', { name: 'Làm mới trả góp', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).financeState.refreshes)).toBe(1)
  await page.clock.install()
  await page.clock.fastForward(65_000)
  expect(await count(page)).toBe(0)
  await expect(page.locator('.aura-metric-carousel__slide').first()).toContainText('500.000đ')
})

test('opening and explicit paging read only requested ledger pages without changing global debt', async ({ page }) => {
  await boot(page)
  await open(page)
  await expect(history(page).getByText('admin-a-first-all-1', { exact: false })).toBeVisible()
  expect(await count(page)).toBe(1)
  expect(await page.evaluate(() => (window as any).financeState.calls[0].query)).toMatchObject({ includeSummary: false, pageSize: 50, cursor: null })
  await history(page).getByRole('button', { name: 'Tải thêm giao dịch' }).click()
  await expect(history(page).getByText('admin-a-second-all-2', { exact: false })).toBeVisible()
  expect(await count(page)).toBe(2)
  await expect(history(page).getByText('2 giao dịch tiền đã tải.', { exact: false })).toBeVisible()
  await expect(history(page).getByRole('button', { name: 'Tải thêm giao dịch' })).toHaveCount(0)
  expect(await page.evaluate(() => (window as any).financeState.calls[1].query.cursor)).toBe('next-1')
  await history(page).getByRole('button', { name: 'Đóng', exact: true }).click()
  await expect(page.locator('.aura-metric-carousel__slide').first()).toContainText('1.500.000đ')
  await open(page)
  await expect(history(page).getByText('admin-a-first-all-3', { exact: false })).toBeVisible()
  expect(await count(page)).toBe(3)
})

test('closing an in-flight history prevents legacy fallback and waits for explicit reopen', async ({ page }) => {
  await boot(page)
  await page.evaluate(() => { (window as any).financeState.defer = true })
  await open(page)
  await expect(history(page).getByRole('status')).toBeVisible()
  await expect.poll(() => count(page)).toBe(1)
  await history(page).getByRole('button', { name: 'Đóng', exact: true }).click()
  await expect(history(page)).toHaveCount(0)
  await page.evaluate(() => (window as any).financeState.resolve(0, 'legacy'))
  await expect.poll(() => page.evaluate(() => (window as any).financeState.settled)).toBe(1)
  expect(await count(page)).toBe(1)
  await open(page)
  await expect.poll(() => count(page)).toBe(2)
  await page.evaluate(() => (window as any).financeState.resolve(1))
  await expect(history(page).getByText('admin-a-first-all-2', { exact: false })).toBeVisible()
})

test('filter changes fence late responses and reset the page chain', async ({ page }) => {
  await boot(page)
  await page.evaluate(() => { (window as any).financeState.defer = true })
  await open(page)
  await expect.poll(() => count(page)).toBe(1)
  await page.getByRole('combobox', { name: 'Lọc chi nhánh công nợ', exact: true }).selectOption('b', { force: true })
  await expect.poll(() => count(page)).toBe(2)
  await page.evaluate(() => (window as any).financeState.resolve(1))
  await expect(history(page).getByText('admin-a-first-b-2', { exact: false })).toBeVisible()
  await page.evaluate(() => (window as any).financeState.resolve(0))
  await expect.poll(() => page.evaluate(() => (window as any).financeState.settled)).toBe(2)
  await expect(history(page).getByText('admin-a-first-all-1', { exact: false })).toHaveCount(0)
  await history(page).getByRole('button', { name: 'Tải thêm giao dịch' }).click()
  await expect.poll(() => count(page)).toBe(3)
  expect(await page.evaluate(() => (window as any).financeState.calls[2].query)).toMatchObject({ branchId: 'b', cursor: 'next-2' })
})

test('account and authority changes close history and reject prior-owner completion', async ({ page }) => {
  await boot(page)
  await page.evaluate(() => { (window as any).financeState.defer = true })
  await open(page)
  await expect.poll(() => count(page)).toBe(1)
  await page.getByRole('button', { name: 'Change account', exact: true }).evaluate((button: HTMLButtonElement) => button.click())
  await expect(history(page)).toHaveCount(0)
  await page.evaluate(() => (window as any).financeState.resolve(0, 'legacy'))
  await expect.poll(() => page.evaluate(() => (window as any).financeState.settled)).toBe(1)
  expect(await count(page)).toBe(1)
  await open(page)
  await expect.poll(() => count(page)).toBe(2)
  await page.evaluate(() => (window as any).financeState.resolve(1))
  await expect(history(page).getByText('admin-b-first-all-2', { exact: false })).toBeVisible()
  await expect(history(page).getByText('admin-a-first', { exact: false })).toHaveCount(0)
  await page.getByRole('button', { name: 'Change authority', exact: true }).evaluate((button: HTMLButtonElement) => button.click())
  await expect(history(page)).toHaveCount(0)
  expect(await count(page)).toBe(2)
})

test('history errors remain visible and user retry keeps summary reads disabled', async ({ page }) => {
  await boot(page)
  await page.evaluate(() => { (window as any).financeState.failure = 'unavailable' })
  await open(page)
  await expect(history(page).getByRole('alert')).toContainText('Dịch vụ sổ cái đang bận')
  await expect(history(page).getByText('Chưa có dòng tiền trong bộ lọc.')).toHaveCount(0)
  await history(page).getByRole('button', { name: 'Thử lại', exact: true }).click()
  await expect(history(page).getByText('admin-a-first-all-2', { exact: false })).toBeVisible()
  await expect(history(page).getByRole('alert')).toHaveCount(0)
  expect(await page.evaluate(() => (window as any).financeState.calls.every((call: any) => call.query.includeSummary === false))).toBe(true)
})

test('compatible legacy type retry stays canonical and skips ledger summaries', async ({ page }) => {
  await boot(page)
  await page.evaluate(() => { (window as any).financeState.failure = 'legacy' })
  await open(page)
  await expect(history(page).getByText('admin-a-first-all-2', { exact: false })).toBeVisible()
  const calls = await page.evaluate(() => (window as any).financeState.calls)
  expect(calls).toHaveLength(2)
  expect(calls[0].query.types).toBeDefined()
  expect(calls[1].query.types).toBeUndefined()
  expect(calls[1].query.includeSummary).toBe(false)
})

test('recording payment while history is closed updates debt without reading the ledger', async ({ page }) => {
  await boot(page)
  await page.getByRole('button', { name: 'Thu tiền của Test learner A', exact: true }).click()
  const payment = page.getByRole('dialog', { name: 'Thu công nợ', exact: true })
  await payment.getByRole('button', { name: 'Ghi khoản thu', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).financeState.payments)).toBe(1)
  await expect(page.getByRole('dialog', { name: 'Thông báo', exact: true })).toBeVisible()
  expect(await count(page)).toBe(0)
  await expect(page.locator('.aura-metric-carousel__slide').first()).toContainText('500.000đ')
})

test('a reversal refreshes the open history once without loading unused summaries', async ({ page }) => {
  await boot(page)
  await open(page)
  await history(page).getByRole('button', { name: 'Tạo bút toán đảo', exact: true }).click()
  await page.getByRole('button', { name: 'Xác nhận tạo bút toán đảo', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).financeState.reversals)).toBe(1)
  await expect.poll(() => count(page)).toBe(2)
  await expect(history(page).getByText('admin-a-first-all-2', { exact: false })).toBeAttached()
  expect(await page.evaluate(() => (window as any).financeState.calls[1].query.includeSummary)).toBe(false)
})
