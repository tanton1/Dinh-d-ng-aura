import { expect, test, type Page } from '@playwright/test'

const url = '/tests/finance-history-ui/index.html'
const payment = (page: Page) => page.getByRole('dialog', { name: 'Thu công nợ', exact: true })
const pending = (page: Page) => page.getByRole('region', { name: 'Yêu cầu tài chính chưa rõ kết quả' })
async function openPayment(page: Page, amount = '100000') {
  await page.getByRole('button', { name: 'Thu tiền của Test learner A', exact: true }).click()
  await expect(payment(page).getByRole('button', { name: 'Ghi khoản thu', exact: true })).toBeEnabled()
  await payment(page).getByRole('spinbutton').fill(amount)
}
async function failNext(page: Page, failure: 'commit-lost' | 'unavailable') {
  await page.evaluate(failure => { (window as any).financeState.intentFailure = failure }, failure)
}
async function openRecovery(page: Page) {
  await page.getByRole('button', { name: 'Xem yêu cầu', exact: true }).click()
  await expect(pending(page)).toBeVisible()
}

test('lost payment response survives reload and inactive funds with the original immutable payload', async ({ page }, info) => {
  await page.goto(url)
  await openPayment(page)
  await failNext(page, 'commit-lost')
  await payment(page).getByRole('button', { name: 'Ghi khoản thu', exact: true }).click()
  await expect(pending(page)).toContainText('100.000đ')
  await expect(payment(page).getByRole('spinbutton')).toBeDisabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
  await page.screenshot({ path: `tmp/finance-intent-validation/payment-recovery-${info.project.name}.png` })
  const original = await page.evaluate(() => (window as any).financeState.intentCalls[0])
  expect(await page.evaluate(() => (window as any).financeState.payments)).toBe(1)
  await page.reload()
  await page.evaluate(() => { (window as any).financeState.cashAccounts = [] })
  await openRecovery(page)
  await pending(page).getByRole('button', { name: 'Kiểm tra / gửi lại yêu cầu' }).click()
  await expect(page.getByRole('dialog', { name: 'Thông báo' })).toContainText('Đã xác nhận giao dịch')
  const replay = await page.evaluate(() => (window as any).financeState.intentCalls[0])
  expect(replay).toEqual(original)
  expect(await page.evaluate(() => (window as any).financeState.payments)).toBe(0)
  expect(await page.evaluate(() => (window as any).financeState.cashCalls.length)).toBe(0)
  await expect(page.getByRole('complementary', { name: 'Yêu cầu cần kiểm tra' })).toHaveCount(0)
})

test('stopping an uncertain refund returns the committed result without a second refund', async ({ page }) => {
  await page.goto(url)
  await openPayment(page, '-50000')
  await failNext(page, 'commit-lost')
  await payment(page).getByRole('button', { name: 'Ghi khoản hoàn tiền' }).click()
  await expect(pending(page)).toContainText('50.000đ')
  await pending(page).getByRole('button', { name: 'Dừng yêu cầu chưa ghi' }).click()
  await expect(page.getByRole('dialog', { name: 'Thông báo' })).toContainText('Đã xác nhận giao dịch')
  const result = await page.evaluate(() => ({ calls: (window as any).financeState.intentCalls, refunds: (window as any).financeState.refunds }))
  expect(result.refunds).toBe(1)
  expect(result.calls.map((call: any) => call.action)).toEqual(['submit', 'cancel'])
  expect(result.calls[0].operation).toEqual(result.calls[1].operation)
})

test('an unavailable attempt blocks editing until durable cancellation, then permits a new operation', async ({ page }) => {
  await page.goto(url)
  await openPayment(page)
  await failNext(page, 'unavailable')
  await payment(page).getByRole('button', { name: 'Ghi khoản thu', exact: true }).click()
  await expect(pending(page)).toBeVisible()
  await expect(payment(page).getByRole('spinbutton')).toBeDisabled()
  await expect(payment(page).getByRole('combobox')).toBeDisabled()
  await pending(page).getByRole('button', { name: 'Dừng yêu cầu chưa ghi' }).click()
  await expect(page.getByRole('dialog', { name: 'Thông báo' })).toContainText('Đã dừng yêu cầu chưa ghi nhận')
  await page.getByRole('dialog', { name: 'Thông báo' }).getByRole('button', { name: 'Đóng', exact: true }).last().click()
  await openPayment(page, '200000')
  await payment(page).getByRole('button', { name: 'Ghi khoản thu', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Thông báo' })).toContainText('Đã xác nhận giao dịch')
  const result = await page.evaluate(() => ({ calls: (window as any).financeState.intentCalls, payments: (window as any).financeState.payments }))
  expect(result.payments).toBe(1)
  expect(result.calls[0].operation.payload.idempotencyKey).toBe(result.calls[1].operation.payload.idempotencyKey)
  expect(result.calls[2].operation.payload.idempotencyKey).not.toBe(result.calls[0].operation.payload.idempotencyKey)
  expect(result.calls[2].operation.payload.amount).toBe(200000)
})

test('a stale open form in another tab cannot submit after the first tab acknowledges success', async ({ page, context }) => {
  const other = await context.newPage()
  await Promise.all([page.goto(url), other.goto(url)])
  await Promise.all([openPayment(page), openPayment(other)])
  await payment(page).getByRole('button', { name: 'Ghi khoản thu', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Thông báo' })).toContainText('Đã xác nhận giao dịch')
  await expect(payment(other).getByRole('button', { name: 'Ghi khoản thu', exact: true })).toBeDisabled()
  await expect(payment(other)).toContainText('Kết quả đã được cập nhật')
  expect(await other.evaluate(() => (window as any).financeState.intentCalls.length)).toBe(0)
  expect(await page.evaluate(() => Object.keys(JSON.parse(localStorage.getItem('synthetic-finance-receipts') || '{}')).length)).toBe(1)
})

test('changing accounts fences an in-flight result and keeps its receipt in the original namespace', async ({ page }) => {
  await page.goto(url)
  await openPayment(page)
  await page.evaluate(() => { (window as any).financeState.intentDefer = true })
  await payment(page).getByRole('button', { name: 'Ghi khoản thu', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).financeState.intentPending.length)).toBe(1)
  await page.getByRole('button', { name: 'Change account' }).evaluate((button: HTMLButtonElement) => button.click())
  await expect(payment(page)).toHaveCount(0)
  await page.evaluate(() => (window as any).financeState.intentPending[0].resolve())
  await expect.poll(() => page.evaluate(async () => {
    const api = (window as any).financeIntentStore
    return (await api.readFinanceIntent({ projectId: 'synthetic-ui-project', ownerUid: 'admin-a', contractId: 'contract-a' }))?.outcome?.state
  })).toBe('committed')
  await expect(page.getByRole('dialog', { name: 'Thông báo' })).toHaveCount(0)
  await expect(page.getByRole('complementary', { name: 'Yêu cầu cần kiểm tra' })).toHaveCount(0)
  expect(await page.evaluate(async () => (window as any).financeIntentStore.readFinanceIntent({ projectId: 'synthetic-ui-project', ownerUid: 'admin-b', contractId: 'contract-a' }))).toBeNull()
})

