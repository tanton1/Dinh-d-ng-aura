test('Student 360 recovers a lost payment after reload even when the installment is already paid', async ({ page }, info) => {
  await page.goto(url + '?workspace=student')
  await page.getByRole('button', { name: 'Quản lý thu tiền' }).click()
  await expect(page.getByRole('combobox').first()).toHaveValue('cash-a')
  await page.getByRole('button', { name: 'Thu tiền', exact: true }).click()
  await failNext(page, 'commit-lost')
  await page.getByRole('alertdialog').getByRole('button', { name: 'Xác nhận', exact: true }).click()
  await expect(pending(page)).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
  await page.screenshot({ path: `tmp/finance-intent-validation/student-recovery-${info.project.name}.png` })
  const original = await page.evaluate(() => (window as any).financeState.intentCalls[0].operation)
  await page.reload()
  await expect(page.getByText('Đã thu', { exact: true })).toBeVisible()
  await openRecovery(page)
  await pending(page).getByRole('button', { name: 'Kiểm tra / gửi lại yêu cầu' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Đã xác nhận giao dịch được ghi nhận' })).toBeVisible()
  const result = await page.evaluate(() => ({ calls: (window as any).financeState.intentCalls, payments: (window as any).financeState.payments, refreshes: (window as any).financeState.projectionRefreshes, cashReads: (window as any).financeState.cashCalls.length }))
  expect(result.calls[0].operation).toEqual(original)
  expect(result.payments).toBe(0)
  expect(result.refreshes).toBe(1)
  expect(result.cashReads).toBe(0)
})

test('Student 360 refund preserves its reason and amount when retrying', async ({ page }) => {
  await page.goto(url + '?workspace=student')
  await page.getByRole('button', { name: 'Quản lý thu tiền' }).click()
  await expect(page.getByRole('combobox').first()).toHaveValue('cash-a')
  await page.getByRole('button', { name: 'Thu tiền', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Xác nhận', exact: true }).click()
  await expect(page.getByText('Đã thu', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Hoàn tác', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('textbox').fill('Synthetic agreed refund')
  await failNext(page, 'commit-lost')
  await page.getByRole('alertdialog').getByRole('button', { name: 'Xác nhận', exact: true }).click()
  await expect(pending(page)).toBeVisible()
  await expect(page.getByRole('alertdialog').getByRole('textbox')).toBeDisabled()
  await pending(page).getByRole('button', { name: 'Kiểm tra / gửi lại yêu cầu' }).click()
  await expect(page.getByText('Chờ thu', { exact: true })).toBeVisible()
  const result = await page.evaluate(() => ({ refunds: (window as any).financeState.refunds, calls: (window as any).financeState.intentCalls }))
  expect(result.refunds).toBe(1)
  expect(result.calls[1].operation).toEqual(result.calls[2].operation)
  expect(result.calls[1].operation.payload.reason).toBe('Synthetic agreed refund')
})
