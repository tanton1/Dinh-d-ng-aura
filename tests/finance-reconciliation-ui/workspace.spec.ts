import { expect, test } from '@playwright/test'

for (const timezoneId of ['Asia/Ho_Chi_Minh', 'UTC', 'America/Los_Angeles']) test.describe(`business dates in ${timezoneId}`, () => {
  test.use({ timezoneId })
  test('ledger evidence converts UTC instants and preserves contract calendar dates', async ({ page }) => {
    await page.goto('/tests/finance-reconciliation-ui/index.html?businessDate=true')
    await page.getByRole('button', { name: /Cần xử lý/ }).click()
    await page.getByRole('button', { name: /Học viên giá trị 0đ/ }).click()
    const dialog = page.getByRole('dialog', { name: 'Bằng chứng đối soát' })
    await expect(dialog.locator('.finance-review-case__ledger')).toContainText('01/11/2026')
    await expect(dialog.locator('.finance-review-case__contract')).toContainText('01/10/2026 – 31/12/2026')
  })
})
test('loads only the report at entry, does not poll, and reads bounded pages on demand', async ({ page }) => {
  await page.clock.install()
  await page.goto('/tests/finance-reconciliation-ui/index.html')
  await expect(page.getByRole('button', { name: /Cần xử lý/ })).toBeVisible()
  await page.clock.fastForward(31000)
  expect(await page.evaluate(() => (window as any).financeCalls)).toMatchObject({ reports: 1, lists: [], details: [], writes: [] })
  await page.getByRole('button', { name: /^Đã khớp/ }).click()
  await expect(page.locator('.finance-review__list li')).toHaveCount(25)
  await page.getByRole('button', { name: 'Tiếp', exact: true }).click()
  await expect(page.locator('.finance-review__list li')).toHaveCount(5)
  expect(await page.evaluate(() => (window as any).financeCalls.lists.map((a: string[]) => a.length))).toEqual([25, 5])
  await page.clock.fastForward(31000)
  expect(await page.evaluate(() => (window as any).financeCalls.reports)).toBe(1)
  await page.getByRole('button', { name: 'Làm mới báo cáo' }).click()
  await expect.poll(() => page.evaluate(() => (window as any).financeCalls.reports)).toBe(2)
})
test('zero-value confirmation requires evidence, reason and consent, then refreshes the report and history', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/tests/finance-reconciliation-ui/index.html')
  await page.getByRole('button', { name: /Cần xử lý/ }).click()
  await page.getByRole('button', { name: /Học viên giá trị 0đ/ }).click()
  const dialog = page.getByRole('dialog', { name: 'Bằng chứng đối soát' })
  await expect(dialog.getByRole('heading', { name: 'Hợp đồng sử dụng buổi' })).toBeVisible()
  expect((await dialog.boundingBox())?.y).toBe(0)
  await dialog.getByLabel('Thao tác đối soát').selectOption('confirm_zero')
  const submit = dialog.getByRole('button', { name: 'Xác nhận giá trị 0đ hợp lệ', exact: true })
  await expect(submit).toBeDisabled()
  await dialog.getByLabel('Lý do và căn cứ').fill('Đã đối chiếu chứng từ gốc')
  await expect(submit).toBeDisabled()
  await dialog.getByRole('checkbox').check()
  await submit.click()
  await expect(dialog.getByRole('status')).toContainText('Đã xử lý')
  await expect(dialog.getByText('Đã xác minh giá trị 0đ', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => (window as any).financeCalls.writes.length)).toBe(1)
  await page.screenshot({ path: 'test-results/finance-reconciliation/detail-mobile.png', fullPage: true })
  await dialog.getByRole('button', { name: 'Đóng bằng chứng' }).click()
  await expect(page.getByRole('button', { name: /Cần xử lý/ })).toContainText('1')
})
test('mobile grouping and excluded evidence stay readable without truncating labels', async ({ page }) => {
  for (const width of [360, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/tests/finance-reconciliation-ui/index.html')
    await expect(page.locator('.finance-report-metrics article')).toHaveCount(4)
    await page.getByRole('button', { name: /Đã loại trừ/ }).click()
    await page.getByLabel('Phân loại đối soát').selectOption('duplicate')
    await expect(page.locator('.finance-review__list li')).toHaveCount(1)
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
    if (width === 390 || width === 1440) await page.screenshot({ path: `test-results/finance-reconciliation/overview-${width}.png`, fullPage: true })
    await page.getByRole('button', { name: /Học viên duplicate/ }).click()
    await expect(page.getByRole('link', { name: 'Xem buổi gốc của bản ghi trùng' })).toHaveAttribute('href', /sessionId=original/)
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog')).not.toBeVisible()
  }
})
