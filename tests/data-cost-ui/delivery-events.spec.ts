import { expect, test, type Page } from '@playwright/test'

const reads = (page: Page) => page.evaluate(() => (window as any).costState.reads.driver)
const emit = (page: Page, value: number, path = 'eatCleanDriverChanges/driver') => page.evaluate(({ path, value }) => (window as any).emitDeliveryRevision(path, value), { path, value })
async function start(page: Page, initial?: Record<string, unknown>) {
  if (initial) await page.addInitScript(value => { (window as any).costInitial = value }, initial)
  await page.clock.install()
  await page.goto('/tests/data-cost-ui/index.html')
}
const settle = async (page: Page) => { await page.clock.runFor(250); await page.waitForTimeout(30) }

test('thirty idle foreground minutes do no callable work; bursts, duplicates and other drivers are coalesced', async ({ page }) => {
  await start(page)
  await expect(page.getByRole('heading', { name: 'Chào Test driver' })).toBeVisible()
  expect(await reads(page)).toBe(1)
  await page.clock.runFor(1_800_000)
  expect(await reads(page)).toBe(1)
  await page.evaluate(() => { for (let n = 1; n <= 30; n++) (window as any).emitDeliveryRevision('eatCleanDriverChanges/driver', n) })
  await settle(page)
  await expect.poll(() => reads(page)).toBe(2)
  await emit(page, 30); await emit(page, 2); await emit(page, 99, 'eatCleanDriverChanges/other')
  await page.clock.runFor(1_800_000)
  expect(await reads(page)).toBe(2)
  await emit(page, 1, 'eatCleanWorkspaceChanges/config')
  await settle(page)
  await expect.poll(() => reads(page)).toBe(3)
})

test('a commit during bootstrap is recovered from the first server marker snapshot', async ({ page }) => {
  await start(page, { delayed: true })
  await expect.poll(() => reads(page)).toBe(1)
  await emit(page, 1)
  await page.evaluate(() => {
    const state = (window as any).costState
    state.jobCode = 'NEW-AFTER-BOOTSTRAP'; state.delayed = false
    state.pending.splice(0).forEach((resolve: () => void) => resolve())
  })
  await settle(page)
  await expect.poll(() => reads(page)).toBe(2)
  await expect(page.getByRole('button', { name: /NEW-AFTER-BOOTSTRAP/ })).toBeVisible()
})

