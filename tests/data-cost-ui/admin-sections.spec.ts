import { expect, test, type Page } from '@playwright/test'
const calls = (page: Page) => page.evaluate(() => (window as any).costState.adminSectionCalls || [])
const state = async (page: Page) => JSON.parse(await page.getByLabel('Section state').innerText())
async function open(page: Page, patch: Record<string, unknown> = {}) {
  await page.clock.install()
  await page.addInitScript(patch => { (window as any).costInitial = patch }, patch)
  await page.goto('/tests/data-cost-ui/index.html?view=admin-sections')
}
test('overlapping tab reads share pending config and retain out-of-order results for their own sections', async ({ page }) => {
  await open(page, { adminHold: true, adminMeals: [{ id: 'm', name: 'Original meal' }] })
  await expect.poll(() => calls(page)).toEqual([['meals', 'config']])
  await page.getByRole('button', { name: 'orders', exact: true }).click()
  await expect.poll(() => calls(page)).toEqual([['meals', 'config'], ['orders']])
  await page.evaluate(() => { (window as any).costState.adminPending.splice(1, 1)[0]() })
  await expect.poll(async () => (await state(page)).data?.summary.byStatus.pending_confirmation).toBe(7)
  expect((await state(page)).ready).toBe(false)
  await page.evaluate(() => { (window as any).costState.adminPending.shift()() })
  await expect.poll(async () => (await state(page)).ready).toBe(true)
  await page.getByRole('button', { name: 'menu', exact: true }).click()
  expect((await state(page)).data.meals[0].name).toBe('Original meal')
  expect((await calls(page)).length).toBe(2)
})
test('a committed section patch survives an older read while other requested sections can finish', async ({ page }) => {
  await open(page, { adminMeals: [{ id: 'm', name: 'Original meal' }] })
  await expect.poll(async () => (await state(page)).ready).toBe(true)
  await page.evaluate(() => { (window as any).costState.adminHold = true; (window as any).costState.adminSeeded = false })
  await page.getByRole('button', { name: 'Refresh sections' }).click()
  await expect.poll(() => calls(page)).toHaveLength(2)
  await page.getByRole('button', { name: 'Apply committed meal' }).click()
  await expect.poll(async () => (await state(page)).data.meals[0].name).toBe('Saved meal')
  await page.evaluate(() => { (window as any).costState.adminPending.shift()() })
  await expect.poll(async () => (await state(page)).refreshing).toBe(false)
  expect((await state(page)).data.meals[0].name).toBe('Saved meal')
  expect((await state(page)).data.seeded).toBe(true)
  expect((await calls(page)).length).toBe(2)
})
test('invalidating inactive stock defers its read until needed and leaves menu/config cached', async ({ page }) => {
  await open(page)
  await expect.poll(async () => (await state(page)).ready).toBe(true)
  await page.getByRole('button', { name: 'inventory', exact: true }).click()
  await expect.poll(async () => (await state(page)).ready).toBe(true)
  expect(await calls(page)).toEqual([['meals', 'config'], ['inventory']])
  await page.getByRole('button', { name: 'menu', exact: true }).click()
  await page.getByRole('button', { name: 'Invalidate stock' }).click()
  await page.clock.runFor(600000)
  expect((await calls(page)).length).toBe(2)
  await page.getByRole('button', { name: 'inventory', exact: true }).click()
  await expect.poll(() => calls(page)).toEqual([['meals', 'config'], ['inventory'], ['inventory']])
})
test('a denied read clears all cached sections and fences another successful response already in flight', async ({ page }) => {
  await open(page, { adminHold: true, adminMeals: [{ id: 'm', name: 'Private meal' }] })
  await expect.poll(() => calls(page)).toHaveLength(1)
  await page.evaluate(() => { (window as any).costState.adminError = 'functions/permission-denied' })
  await page.getByRole('button', { name: 'orders', exact: true }).click()
  await expect.poll(() => calls(page)).toHaveLength(2)
  await page.evaluate(() => { (window as any).costState.adminPending.splice(1, 1)[0]() })
  await expect.poll(async () => (await state(page)).error).toBe('Fixture admin catalog unavailable')
  await page.evaluate(() => { (window as any).costState.adminPending.shift()() })
  await page.getByRole('button', { name: 'menu', exact: true }).click()
  await page.clock.runFor(600000)
  expect((await state(page)).data).toBeNull()
  expect((await calls(page)).length).toBe(2)
})

test('active stock invalidation preserves the mounted view while refreshing only stock', async ({ page }) => {
  await open(page)
  await expect.poll(async () => (await state(page)).ready).toBe(true)
  await page.getByRole('button', { name: 'inventory', exact: true }).click()
  await expect.poll(async () => (await state(page)).ready).toBe(true)
  await page.evaluate(() => { (window as any).costState.adminHold = true })
  await page.getByRole('button', { name: 'Invalidate stock' }).click()
  await expect.poll(() => calls(page)).toEqual([['meals', 'config'], ['inventory'], ['inventory']])
  expect((await state(page)).ready).toBe(true)
  expect((await state(page)).loading).toBe(false)
  await expect.poll(async () => (await state(page)).refreshing).toBe(true)
  await page.evaluate(() => { (window as any).costState.adminPending.shift()() })
  await expect.poll(async () => (await state(page)).refreshing).toBe(false)
})

test('patching a dirty section fences the old read and resumes its outstanding reconciliation', async ({ page }) => {
  await open(page, { adminInventory: [{ id: 'i', capacity: 2 }] })
  await expect.poll(async () => (await state(page)).ready).toBe(true)
  await page.getByRole('button', { name: 'inventory', exact: true }).click()
  await expect.poll(async () => (await state(page)).data?.inventory[0]?.capacity).toBe(2)
  await page.evaluate(() => { (window as any).costState.adminHold = true })
  await page.getByRole('button', { name: 'Invalidate stock' }).click()
  await expect.poll(() => calls(page)).toHaveLength(3)
  await page.evaluate(() => { (window as any).costState.adminInventory = [{ id: 'i', capacity: 9 }, { id: 'concurrent', capacity: 5 }] })
  await page.getByRole('button', { name: 'Apply committed stock' }).click()
  await expect.poll(() => calls(page)).toHaveLength(4)
  await expect.poll(async () => (await state(page)).refreshing).toBe(true)
  await page.evaluate(() => { (window as any).costState.adminPending.shift()() })
  expect((await state(page)).data.inventory[0].capacity).toBe(9)
  await page.evaluate(() => { (window as any).costState.adminPending.shift()() })
  await expect.poll(async () => (await state(page)).data.inventory.map((row: any) => row.id)).toEqual(['i', 'concurrent'])
  await expect.poll(async () => (await state(page)).refreshing).toBe(false)
})
