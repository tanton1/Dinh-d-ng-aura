import { expect, test, type Page } from '@playwright/test'
const counts = (page: Page) => page.evaluate(() => ({ admin: (window as any).costState.adminReads || 0, dispatch: (window as any).costState.dispatchCalls.length }))
const ready = (page: Page) => expect(page.getByText('Cập nhật khi có thay đổi', { exact: true })).toBeVisible()
const tab = (page: Page, name: string) => page.getByRole('tab', { name, exact: true }).click()
async function open(page: Page, patch: Record<string, unknown> = {}) {
  await page.clock.install()
  await page.addInitScript(patch => { (window as any).costInitial = patch }, patch)
  await page.goto('/tests/data-cost-ui/index.html?view=dispatch-parent')
}

test('full dispatch route has one bootstrap and no admin inventory read, including idle/hover/refresh', async ({ page }) => {
  await open(page); await ready(page)
  await page.clock.runFor(3600000)
  expect(await counts(page)).toEqual({ admin: 0, dispatch: 1 })
  await page.getByRole('tab', { name: 'Thực đơn', exact: true }).hover()
  await page.clock.runFor(500)
  expect(await counts(page)).toEqual({ admin: 0, dispatch: 1 })
  await expect(page.locator('.eat-clean-stats')).toHaveCount(0)
  await expect(page.locator('.eat-clean-live-state')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Làm mới', exact: true })).toHaveCount(1)
  await page.getByRole('button', { name: 'Làm mới', exact: true }).click()
  await expect.poll(() => counts(page)).toEqual({ admin: 0, dispatch: 2 })
})

test('other tabs load missing sections on demand and reuse shared sections across tab changes', async ({ page }) => {
  await open(page); await ready(page)
  await tab(page, 'Đơn hàng'); await expect(page.locator('.eat-clean-stats')).toBeVisible()
  expect((await counts(page)).admin).toBe(1)
  await tab(page, 'Tồn kho'); await tab(page, 'Thực đơn'); await tab(page, 'Vận hành')
  expect((await counts(page)).admin).toBe(2)
  expect(await page.evaluate(() => (window as any).costState.adminSectionCalls)).toEqual([['orders', 'config'], ['meals', 'inventory']])
  await tab(page, 'Điều phối'); await ready(page)
  await expect(page.locator('.eat-clean-stats')).toHaveCount(0)
  await tab(page, 'Đơn hàng'); await expect(page.locator('.eat-clean-stats')).toBeVisible()
  expect((await counts(page)).admin).toBe(2)
})

test('catalog failure is isolated from dispatch and retries only on explicit request', async ({ page }) => {
  await open(page, { adminInitialTab: 'orders', adminError: 'unavailable' })
  await expect(page.getByText('Fixture admin catalog unavailable')).toBeVisible()
  expect((await counts(page)).admin).toBe(1)
  await tab(page, 'Điều phối'); await ready(page)
  await expect(page.getByText('Fixture admin catalog unavailable')).toHaveCount(0)
  await page.clock.runFor(600000)
  expect((await counts(page)).admin).toBe(1)
  await tab(page, 'Đơn hàng')
  await expect(page.getByText('Fixture admin catalog unavailable')).toBeVisible()
  await page.evaluate(() => { (window as any).costState.adminError = '' })
  await page.getByRole('button', { name: 'Thử tải lại' }).click()
  await expect(page.locator('.eat-clean-stats')).toBeVisible()
  expect((await counts(page)).admin).toBe(2)
})

test('a pending catalog read does not delay dispatch or create another request on return', async ({ page }) => {
  await open(page, { adminInitialTab: 'orders', adminHold: true })
  await expect.poll(() => counts(page)).toEqual({ admin: 1, dispatch: 0 })
  await tab(page, 'Điều phối'); await ready(page)
  await expect(page.locator('main.admin-eat-clean-page')).toHaveAttribute('aria-busy', 'false')
  await page.evaluate(() => { (window as any).costState.adminPending.shift()() })
  await expect(page.locator('.eat-clean-stats')).toHaveCount(0)
  await tab(page, 'Đơn hàng'); await expect(page.locator('.eat-clean-stats')).toBeVisible()
  expect((await counts(page)).admin).toBe(1)
})

test('account changes reset private catalog state and fence a delayed previous-account result', async ({ page }) => {
  await open(page, { adminInitialTab: 'orders', adminHold: true, adminBadge: 7 })
  await expect.poll(() => counts(page)).toEqual({ admin: 1, dispatch: 0 })
  await page.evaluate(() => { (window as any).costState.adminBadge = 9 })
  await page.getByRole('button', { name: 'Change admin account' }).click()
  await expect.poll(() => counts(page)).toEqual({ admin: 2, dispatch: 0 })
  await page.evaluate(() => { (window as any).costState.adminPending.shift()() })
  await expect(page.locator('.eat-clean-stats')).toHaveCount(0)
  await page.evaluate(() => { (window as any).costState.adminPending.shift()() })
  await expect(page.locator('.eat-clean-stats strong').first()).toHaveText('9')
})

test('role revocation clears the workspace and never restores a delayed catalog response', async ({ page }) => {
  await open(page, { adminInitialTab: 'orders', adminHold: true })
  await expect.poll(() => counts(page)).toEqual({ admin: 1, dispatch: 0 })
  await page.getByRole('button', { name: 'Revoke admin' }).click()
  await expect(page.getByRole('heading', { name: 'Không có quyền quản trị Eat Clean' })).toBeVisible()
  await page.evaluate(() => { (window as any).costState.adminPending.shift()(); (window as any).costState.adminHold = false; (window as any).costState.adminBadge = 9 })
  await expect(page.locator('.eat-clean-stats')).toHaveCount(0)
  await page.getByRole('button', { name: 'Restore admin' }).click()
  await expect(page.locator('.eat-clean-stats strong').first()).toHaveText('9')
  expect((await counts(page)).admin).toBe(2)
})

test('an unseeded catalog cannot block dispatch or automatically initialize business data', async ({ page }) => {
  await open(page, { adminSeeded: false }); await ready(page)
  expect((await counts(page)).admin).toBe(0)
  await tab(page, 'Đơn hàng')
  await expect(page.getByRole('button', { name: 'Khởi tạo thực đơn mẫu', exact: true })).toBeVisible()
  await tab(page, 'Điều phối'); await ready(page)
  expect(await page.evaluate(() => (window as any).costState.adminInitializations || 0)).toBe(0)
  expect((await counts(page)).admin).toBe(1)
})

test('post-mutation reconciliation cannot reuse an older in-flight catalog read', async ({ page }) => {
  await open(page, { adminInitialTab: 'orders', adminSeeded: false })
  await expect(page.getByRole('button', { name: 'Khởi tạo thực đơn mẫu', exact: true })).toBeVisible()
  await page.evaluate(() => { (window as any).costState.adminHold = true })
  await page.getByRole('button', { name: 'Làm mới', exact: true }).click()
  await expect.poll(() => counts(page)).toEqual({ admin: 2, dispatch: 0 })
  await page.getByRole('button', { name: 'Khởi tạo thực đơn mẫu', exact: true }).click()
  await expect.poll(() => counts(page)).toEqual({ admin: 3, dispatch: 0 })
  await page.evaluate(() => { (window as any).costState.adminPending.shift()() })
  await expect(page.locator('.eat-clean-seed-state')).toBeVisible()
  await page.evaluate(() => { (window as any).costState.adminPending.shift()() })
  await expect(page.locator('.eat-clean-seed-state')).toHaveCount(0)
  await expect(page.getByRole('tabpanel')).toBeVisible()
  expect((await counts(page)).admin).toBe(3)
})

