import { expect, test, type Page } from '@playwright/test'

const reads = (page: Page, kind: string) => page.evaluate(kind => (window as any).costState.reads[kind], kind)
async function available(page: Page, visible: boolean, online: boolean) {
  await page.evaluate(({ visible, online }) => {
    Object.defineProperty(document, 'visibilityState', { configurable: true, value: visible ? 'visible' : 'hidden' })
    Object.defineProperty(navigator, 'onLine', { configurable: true, value: online })
    document.dispatchEvent(new Event('visibilitychange'))
    window.dispatchEvent(new Event(online ? 'online' : 'offline'))
  }, { visible, online })
}
test('driver selection does not reload; hidden/offline ten minutes does no work and resume never overlaps', async ({ page }) => {
  await page.clock.install()
  await page.goto('/tests/data-cost-ui/index.html')
  await expect(page.getByRole('heading', { name: 'Chào Test driver' })).toBeVisible()
  expect(await reads(page, 'driver')).toBe(1)
  await page.getByRole('button', { name: /ORDER-A/ }).click()
  await expect(page.getByRole('button', { name: 'Nhận chuyến giao' })).toBeVisible()
  expect(await reads(page, 'driver')).toBe(1)
  await available(page, false, true)
  await page.clock.runFor(600_000)
  expect(await reads(page, 'driver')).toBe(1)
  await available(page, true, false)
  await page.clock.runFor(600_000)
  expect(await reads(page, 'driver')).toBe(1)
  await page.evaluate(() => { (window as any).costState.delayed = true; (window as any).emitDeliveryRevision('eatCleanDriverChanges/driver', 1) })
  await available(page, true, true)
  await expect.poll(() => reads(page, 'driver')).toBe(2)
  await page.clock.runFor(120_000)
  expect(await reads(page, 'driver')).toBe(2)
  await page.getByRole('button', { name: 'Nhận chuyến giao' }).click()
  await expect(page.getByRole('button', { name: 'Tôi đã đến bếp' })).toBeVisible()
  await page.evaluate(() => { (window as any).costState.delayed = false; (window as any).costState.pending.splice(0).forEach((resolve: () => void) => resolve()) })
  await page.clock.runFor(250)
  await expect(page.getByRole('button', { name: 'Tôi đã đến bếp' })).toBeVisible()
  expect(await reads(page, 'driver')).toBe(3)
})

test('dispatcher pauses in settings and background reads preserve an unsaved configuration', async ({ page }) => {
  await page.clock.install()
  await page.goto('/tests/data-cost-ui/index.html?view=dispatch')
  await expect(page.getByText('Không có đơn chờ gán', { exact: true })).toBeVisible()
  expect(await reads(page, 'dispatch')).toBe(1)
  await page.getByRole('tab', { name: 'Phí giao & SLA' }).click()
  await page.getByLabel('Tên bếp', { exact: true }).fill('Unsaved kitchen')
  await page.clock.runFor(600_000)
  expect(await reads(page, 'dispatch')).toBe(1)
  await page.getByRole('button', { name: 'Làm mới', exact: true }).click()
  await expect.poll(() => reads(page, 'dispatch')).toBe(2)
  await expect(page.getByLabel('Tên bếp', { exact: true })).toHaveValue('Unsaved kitchen')
  await page.getByRole('tab', { name: 'Điều phối trực tiếp' }).click()
  await available(page, false, true)
  await page.clock.runFor(600_000)
  expect(await reads(page, 'dispatch')).toBe(2)
  await available(page, true, true)
  await page.clock.runFor(1000)
  expect(await reads(page, 'dispatch')).toBe(2)
})

test('tracking pauses while hidden, ignores old-order responses and stops automatic reads after delivery', async ({ page }) => {
  await page.clock.install()
  await page.goto('/tests/data-cost-ui/index.html?view=tracking')
  await expect(page.getByText('order-a', { exact: true })).toBeVisible()
  expect(await reads(page, 'tracking')).toBe(1)
  await available(page, false, true)
  await page.clock.runFor(600_000)
  expect(await reads(page, 'tracking')).toBe(1)
  await page.evaluate(() => { (window as any).costState.delayed = true; (window as any).emitDeliveryRevision('eatCleanOrderChanges/order-a', 1) })
  await available(page, true, true)
  await expect.poll(() => reads(page, 'tracking')).toBe(2)
  await page.evaluate(() => { (window as any).costState.terminal = true })
  await page.getByRole('button', { name: 'Change order' }).click()
  await expect.poll(() => reads(page, 'tracking')).toBe(3)
  await page.evaluate(() => {
    const state = (window as any).costState
    state.delayed = false; state.terminal = true
    state.pending.splice(0).reverse().forEach((resolve: () => void) => resolve())
  })
  await expect(page.getByText('order-b', { exact: true })).toBeVisible()
  await expect(page.getByText('order-a', { exact: true })).toBeHidden()
  await page.clock.runFor(600_000)
  expect(await reads(page, 'tracking')).toBe(3)
})

test('ten Progress tab switches retain base listeners and photo listener is shared only by body/history', async ({ page }) => {
  await page.goto('/tests/data-cost-ui/index.html?view=progress')
  const base = () => page.evaluate(() => (window as any).costState.subscriptions.filter((name: string) => /^(weight|body|checkins):/.test(name)))
  const active = () => page.evaluate(() => [...(window as any).costState.active].sort())
  await expect.poll(async () => (await base()).length).toBe(6) // StrictMode probe plus mounted listeners.
  const original = await base()
  expect((await active()).some((key: string) => key.startsWith('photos:'))).toBe(false)
  await page.getByRole('button', { name: 'Cơ thể', exact: true }).click()
  const photosBefore = await page.evaluate(() => (window as any).costState.subscriptions.filter((key: string) => key.startsWith('photos:')).length)
  for (let index = 0; index < 10; index++) await page.getByRole('button', { name: index % 2 ? 'Cơ thể' : 'Nhật ký', exact: true }).click()
  expect(await base()).toEqual(original)
  expect(await page.evaluate(() => (window as any).costState.subscriptions.filter((key: string) => key.startsWith('photos:')).length)).toBe(photosBefore)
  await page.getByRole('button', { name: 'Tổng quan', exact: true }).click()
  expect((await active()).some((key: string) => key.startsWith('photos:'))).toBe(false)
  await page.getByRole('button', { name: 'Change account' }).click()
  await expect.poll(async () => (await active()).every((key: string) => key.endsWith(':student-b'))).toBe(true)
})
