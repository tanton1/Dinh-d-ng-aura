import { expect, test, type Page } from '@playwright/test'
const path = '/tests/data-cost-ui/index.html?view=progress'
const calls = (page: Page) => page.evaluate(() => (window as any).costState.summaryCalls)
const card = (page: Page) => page.locator('section[aria-labelledby="progress-adherence-title"]')
async function open(page: Page, config = {}, time = '2026-10-24T12:00:00+07:00') {
  await page.clock.install({ time: new Date(time) })
  await page.addInitScript(config => { (window as any).costInitial = config }, config)
  await page.goto(path)
}
const finish = (page: Page, index: number, error?: string) => page.evaluate(({ index, error }) => (window as any).costState.summaryPending[index](error), { index, error })

test('30 days read one daily summary window, 90 days read three; an idle hour never polls raw history', async ({ page }) => {
  await open(page)
  await expect(card(page).getByText('30/30 ngày đủ khung bữa')).toBeVisible()
  expect(await calls(page)).toHaveLength(1)
  await page.clock.runFor(3_600_000)
  expect(await calls(page)).toHaveLength(1)
  await page.getByRole('button', { name: '90 ngày', exact: true }).click()
  await expect(card(page).getByText('90/90 ngày đủ khung bữa')).toBeVisible()
  const requests = await calls(page)
  expect(requests).toHaveLength(4)
  expect(requests.slice(1).map((request: any) => [request.fromDate, request.toDate])).toEqual([
    ['2026-07-27', '2026-08-26'], ['2026-08-27', '2026-09-26'], ['2026-09-27', '2026-10-24'],
  ])
  expect(await page.evaluate(() => (window as any).costState.subscriptions.filter((name: string) => /^(meals|water|activity):/.test(name)))).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await card(page).screenshot({ path: test.info().outputPath('progress-summary.png') })
})

test('body/history do not reload nutrition; changing period there waits until overview', async ({ page }) => {
  await open(page)
  await expect(card(page).getByText('30/30 ngày đủ khung bữa')).toBeVisible()
  for (const name of ['Cơ thể', 'Nhật ký', 'Cơ thể', 'Tổng quan']) await page.getByRole('button', { name, exact: true }).click()
  expect(await calls(page)).toHaveLength(1)
  await page.getByRole('button', { name: 'Cơ thể', exact: true }).click()
  await page.getByRole('button', { name: '90 ngày', exact: true }).click()
  await page.clock.runFor(60_000)
  expect(await calls(page)).toHaveLength(1)
  await page.getByRole('button', { name: 'Tổng quan', exact: true }).click()
  await expect(card(page).getByText('90/90 ngày đủ khung bữa')).toBeVisible()
  expect(await calls(page)).toHaveLength(4)
})

