import { expect, test, type Page } from '@playwright/test'
const marker = 'users/account-a/workspaceChanges/operations'
const calls = (page: Page) => page.evaluate(() => (window as any).workoutCalls)
const counts = async (page: Page) => (await calls(page)).reduce((result: Record<string, number>, item: { kind: string }) => ({ ...result, [item.kind]: (result[item.kind] || 0) + 1 }), {})
const emit = (page: Page, values: Record<string, string>, path = marker) => page.evaluate(({ path, values }) => (window as any).workspaceEmit(path, values), { path, values })
async function open(page: Page) {
  await page.clock.install({ time: new Date('2026-10-24T05:00:00Z') })
  await page.goto('/tests/workspace-sync-ui/index.html?screen=workout')
  await page.clock.runFor(300)
  await expect(page.getByText('Giáo án account-a v1', { exact: true })).toBeVisible()
  expect(await counts(page)).toEqual({ studentTrainingPlan: 1 })
}
async function history(page: Page) {
  await page.getByRole('button', { name: 'Lịch sử & tiến bộ', exact: true }).click()
  await page.clock.runFor(300)
  await expect(page.getByText('Buổi 25', { exact: true })).toBeVisible()
}

test('plan reads once, never loads history while idle, and consumes only plan revisions', async ({ page }) => {
  await open(page)
  await page.clock.fastForward(3_600_000)
  await emit(page, { studentWorkoutHistoryVersion: '0001', studentScheduleVersion: '0001' })
  await emit(page, { studentTrainingPlanVersion: '0001' }, 'users/account-b/workspaceChanges/operations')
  await page.clock.runFor(400)
  expect(await counts(page)).toEqual({ studentTrainingPlan: 1 })
  await page.evaluate(() => { (window as any).planRevision = 2 })
  await emit(page, { studentTrainingPlanVersion: '0001' })
  await emit(page, { studentTrainingPlanVersion: '0001' })
  await page.clock.runFor(400)
  await expect(page.getByText('Giáo án account-a v2', { exact: true })).toBeVisible()
  expect(await counts(page)).toEqual({ studentTrainingPlan: 2 })
})

test('history loads on demand, appends a cursor once, and labels totals as loaded rows', async ({ page }) => {
  await open(page); await history(page)
  await expect(page.getByText('Thống kê từ 25 nhật ký đã tải; còn nhật ký cũ hơn.')).toBeVisible()
  await page.getByRole('button', { name: 'Tải thêm nhật ký', exact: true }).click()
  await page.clock.runFor(300)
  await expect(page.getByText('Buổi 1', { exact: true })).toHaveCount(1)
  await expect(page.getByText('Buổi 27', { exact: true })).toBeVisible()
  await expect(page.getByText('Thống kê từ 27 nhật ký đã tải.')).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('workout-history.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect((await calls(page)).filter((item: any) => item.kind === 'studentWorkoutHistory').map((item: any) => item.cursor)).toEqual([null, 'cursor-25'])
  await page.getByRole('button', { name: 'Giáo án của tôi', exact: true }).click()
  await page.clock.runFor(300)
  await history(page)
  expect(await counts(page)).toEqual({ studentTrainingPlan: 1, studentWorkoutHistory: 2 })
  await emit(page, { studentTrainingPlanVersion: '0001' })
  await page.clock.runFor(300)
  expect(await counts(page)).toEqual({ studentTrainingPlan: 1, studentWorkoutHistory: 2 })
})

test('hidden and offline revisions coalesce until resume without periodic network calls', async ({ page }) => {
  await open(page); await history(page)
  await page.evaluate(() => {
    (window as any).workspaceHidden = true
    ;(window as any).workoutOnline = false
    Object.defineProperty(navigator, 'onLine', { configurable: true, get: () => (window as any).workoutOnline })
  })
  await emit(page, { studentWorkoutHistoryVersion: '0001' })
  await emit(page, { studentWorkoutHistoryVersion: '0002' })
  await page.clock.fastForward(3_600_000)
  expect(await counts(page)).toEqual({ studentTrainingPlan: 1, studentWorkoutHistory: 1 })
  await page.evaluate(() => { (window as any).workspaceHidden = false; document.dispatchEvent(new Event('visibilitychange')) })
  await page.clock.runFor(300)
  expect(await counts(page)).toEqual({ studentTrainingPlan: 1, studentWorkoutHistory: 1 })
  await page.evaluate(() => { (window as any).workoutOnline = true; window.dispatchEvent(new Event('online')) })
  await page.clock.runFor(400)
  expect(await counts(page)).toEqual({ studentTrainingPlan: 1, studentWorkoutHistory: 2 })
})

test('history signal during append discards the stale append and reconciles one first page', async ({ page }) => {
  await open(page); await history(page)
  await page.evaluate(() => { (window as any).workoutPageDelay = 1000 })
  await page.getByRole('button', { name: 'Tải thêm nhật ký', exact: true }).click()
  await page.clock.runFor(10)
  await emit(page, { studentWorkoutHistoryVersion: '0001' })
  await page.clock.runFor(1400)
  await expect(page.getByText('Buổi 27', { exact: true })).toHaveCount(0)
  expect((await calls(page)).filter((item: any) => item.kind === 'studentWorkoutHistory').map((item: any) => item.cursor)).toEqual([null, 'cursor-25', null])
  await page.clock.fastForward(3_600_000)
  expect(await counts(page)).toEqual({ studentTrainingPlan: 1, studentWorkoutHistory: 3 })
})

test('old account responses cannot repopulate personal data after switching accounts', async ({ page }) => {
  await open(page); await history(page)
  await page.evaluate(() => { (window as any).workoutDelay = 1500 })
  await emit(page, { studentTrainingPlanVersion: '0001', studentWorkoutHistoryVersion: '0001' })
  await page.clock.runFor(250)
  await page.evaluate(() => { (window as any).workoutDelay = 0; (window as any).workspaceAccount('account-b') })
  await page.clock.runFor(300)
  await expect(page.getByText('Giáo án account-b v1', { exact: true })).toBeVisible()
  await page.clock.runFor(2000)
  await expect(page.getByText('Giáo án account-a v1', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Buổi 25', { exact: true })).toHaveCount(0)
  expect(await page.evaluate(() => (window as any).workspaceActivePaths())).not.toContain(marker)
})

test('revoked access clears rows; transient failure retries only on explicit action', async ({ page }) => {
  await open(page); await history(page)
  await page.evaluate(() => { (window as any).workoutDenied = true })
  await emit(page, { studentWorkoutHistoryVersion: '0001' })
  await page.clock.runFor(400)
  await expect(page.getByText('Buổi 25', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('alert')).toContainText('thu hồi quyền')
  await page.evaluate(() => { (window as any).workoutDenied = false; (window as any).workoutFails = true })
  await page.getByRole('button', { name: 'Làm mới lịch sử', exact: true }).click()
  await page.clock.runFor(400)
  const before = await counts(page)
  await page.clock.fastForward(3_600_000)
  expect(await counts(page)).toEqual(before)
  await page.evaluate(() => { (window as any).workoutFails = false })
  await page.getByRole('button', { name: 'Làm mới lịch sử', exact: true }).click()
  await page.clock.runFor(400)
  await expect(page.getByText('Buổi 25', { exact: true })).toBeVisible()
})

