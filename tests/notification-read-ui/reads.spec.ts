import { expect, test, type Page } from '@playwright/test'

type Counts = Record<string, number>
const tab = (page: Page, id: string) => page.locator(`[role="tab"][aria-controls="push-panel-${id}"]`)
const metric = (page: Page, label: string) => page.locator('.push-metric').filter({ hasText: label }).locator('strong')
async function counts(page: Page): Promise<Counts> {
  return page.evaluate(() => (window as any).notificationFixture.calls.reduce((result: Counts, row: { name: string }) => {
    result[row.name] = (result[row.name] ?? 0) + 1; return result
  }, {}))
}
async function expectDelta(page: Page, before: Counts, expected: Counts) {
  await expect.poll(async () => {
    const after = await counts(page)
    return Object.fromEntries([...new Set([...Object.keys(before), ...Object.keys(after)])]
      .map(key => [key, (after[key] ?? 0) - (before[key] ?? 0)] as const).filter(([, value]) => value))
  }).toEqual(expected)
}
async function release(page: Page, name: string, owner?: string) {
  await page.evaluate(async ({ name, owner }) => {
    (window as any).notificationFixture.release(name, owner)
    await new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve())))
  }, { name, owner })
}
async function open(page: Page, query = '') {
  await page.goto(`/tests/notification-read-ui/index.html${query}`)
  await expect(page.getByRole('heading', { name: 'Push Notifications', exact: true })).toBeVisible()
  if (!query.includes('hold=overview')) {
    await expect(metric(page, 'Học viên hoạt động')).toHaveText(query.includes('fail=overview') ? '—' : '111')
    if (query.includes('fail=overview') || query.includes('fail=settings')) await expect(page.getByRole('alert')).toBeVisible()
    await expect(page.getByTestId('push-overview').getByRole('button', { name: 'Làm mới', exact: true })).toBeEnabled()
  }
}
async function compose(page: Page) {
  await tab(page, 'compose').click()
  await expect(page.getByTestId('push-composer')).toBeVisible()
  await expect.poll(async () => (await counts(page)).templates ?? 0).toBeGreaterThan(0)
}
async function fillDraft(page: Page) {
  await page.getByPlaceholder('Ví dụ: Đến giờ cập nhật bữa trưa').fill('Fixture draft')
  await page.getByPlaceholder('Thông điệp bạn muốn gửi đến học viên…').fill('Review this fixture message')
}
async function library(page: Page) {
  await page.getByRole('button', { name: /Thư viện mẫu/ }).click()
  return page.getByRole('dialog', { name: 'Thư viện mẫu Push' })
}

