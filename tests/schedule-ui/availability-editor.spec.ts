import { expect, test } from '@playwright/test'

test('availability editor loads only on demand and preserves selection, busy guards, save errors and retry', async ({ page }) => {
  const requests: string[] = []
  page.on('request', request => { if (request.url().includes('/ScheduleAvailabilityEditor.tsx')) requests.push(request.url()) })
  await page.goto('/tests/schedule-ui/index.html')
  await expect(page.locator('.schedule-cell').filter({ hasText: 'Lan' })).toHaveCount(1)
  expect(requests).toHaveLength(0)
  await page.getByRole('tab', { name: 'Học viên', exact: true }).click()
  const student = page.locator('#schedule-student-a')
  await expect(student).toBeVisible()
  expect(requests).toHaveLength(0)
  await student.getByRole('button', { name: 'Lịch rảnh', exact: true }).click()
  const editor = student.locator('.branch-schedule__availability-editor')
  await expect(editor.getByRole('region', { name: 'Lịch rảnh của Lan' })).toBeVisible()
  expect(requests).toHaveLength(1)
  await expect(editor).toContainText('3 khung đã chọn')
  await expect(editor.getByRole('button', { name: 'Mở cho học viên đến hết tuần' })).toHaveCount(0)
  await editor.getByRole('button', { name: 'Thứ 2 7 giờ', exact: true }).click()
  await expect(editor).toContainText('4 khung đã chọn')
  await page.evaluate(() => { (window as any).__holdAvailabilitySave = true; (window as any).__failAvailabilitySave = true })
  await editor.getByRole('button', { name: 'Lưu lịch rảnh' }).click()
  await expect(editor.getByRole('button', { name: 'Đang lưu' })).toBeDisabled()
  await expect(editor.getByRole('button', { name: 'Thứ 2 7 giờ, đã chọn', exact: true })).toBeDisabled()
  await expect(editor.getByRole('button', { name: 'Đóng', exact: true })).toBeEnabled()
  await expect(page.getByLabel('Chọn chi nhánh')).toBeDisabled()
  await page.evaluate(() => (window as any).__releaseAvailabilitySave())
  await expect(editor.getByRole('alert')).toHaveText('Không lưu được lịch rảnh; hãy thử lại')
  await expect(editor).toContainText('4 khung đã chọn')
  await expect(editor.getByRole('button', { name: 'Lưu lịch rảnh' })).toBeEnabled()
  await page.evaluate(() => { (window as any).__holdAvailabilitySave = false; (window as any).__failAvailabilitySave = false })
  await editor.getByRole('button', { name: 'Lưu lịch rảnh' }).click()
  await expect(page.getByText('Đã cập nhật lịch rảnh của Lan.', { exact: true })).toBeVisible()
  await expect(editor.getByRole('alert')).toHaveCount(0)
  const calls = await page.evaluate(() => (window as any).__scheduleCalls.filter((item: any) => item.operation === 'save-availability'))
  expect(calls).toHaveLength(2)
  for (const { input } of calls) expect(input).toMatchObject({ studentId: 'a', branchId: 'b', expectedRevision: 1, availableSlots: ['T2-6', 'T3-6', 'T4-6', 'T2-7'], confirmBelowMinimum: true })
  await editor.getByRole('button', { name: 'Đóng', exact: true }).click()
  await expect(editor).toHaveCount(0)
  expect(requests).toHaveLength(1)
})

test('lazy availability editor retains admin locked-week reopen controls and request scope', async ({ page }) => {
  await page.addInitScript(() => { (window as any).__enableScheduleListener = true })
  await page.goto('/tests/schedule-ui/index.html')
  await expect(page.locator('.schedule-cell').filter({ hasText: 'Lan' })).toHaveCount(1)
  await page.evaluate(async () => {
    const { weeklyViewFixture } = await import('/tests/schedule-ui/service.ts')
    const call = (window as any).__scheduleCalls.find((item: any) => item.operation === 'weekly-view')
    const payload = weeklyViewFixture(call.input)
    payload.students[0] = { ...payload.students[0], availabilityStatus: 'locked', availabilityLocked: true }
    ;(window as any).__emitScheduleSnapshot('ptScheduleWeeklyViews', payload)
    ;(window as any).__holdAvailabilityReopen = true
  })
  await page.getByRole('tab', { name: 'Học viên', exact: true }).click()
  const student = page.locator('#schedule-student-a')
  await student.getByRole('button', { name: 'Lịch rảnh đã khóa', exact: true }).click()
  const editor = student.locator('.branch-schedule__availability-editor')
  await editor.getByRole('button', { name: 'Mở cho học viên đến hết tuần' }).click()
  await expect(editor.getByRole('button', { name: 'Đang mở', exact: true })).toBeDisabled()
  await expect(editor.getByRole('button', { name: 'Đang lưu', exact: true })).toBeDisabled()
  await expect(editor.getByRole('button', { name: 'Thứ 2 6 giờ, đã chọn', exact: true })).toBeDisabled()
  await page.evaluate(() => (window as any).__releaseAvailabilityReopen())
  await expect(page.getByText('Đã mở lịch rảnh cho Lan đến hết tuần.', { exact: true })).toBeVisible()
  await expect(editor.getByRole('button', { name: 'Mở cho học viên đến hết tuần' })).toHaveCount(0)
  await expect(editor.getByRole('button', { name: 'Lưu lịch rảnh', exact: true })).toBeEnabled()
  const calls = await page.evaluate(() => (window as any).__scheduleCalls.filter((item: any) => item.operation === 'reopen-availability'))
  expect(calls).toHaveLength(1)
  expect(calls[0].input).toMatchObject({ studentId: 'a', branchId: 'b', expectedRevision: 1 })
})
