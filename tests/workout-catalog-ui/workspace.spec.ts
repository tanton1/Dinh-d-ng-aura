import { expect, test, type Page } from '@playwright/test'

const calls = (page: Page) => page.evaluate(() => (window as unknown as { catalogCalls: Array<{ query?: string }> }).catalogCalls)
async function openProgram(page: Page) {
  await page.goto('/tests/workout-catalog-ui/index.html')
  await expect(page.getByRole('button', { name: 'Làm mới', exact: true })).toBeEnabled()
  expect(await calls(page)).toEqual([])
  await page.getByRole('button', { name: 'Giáo án', exact: true }).click()
}

test('empty catalog finishes once, remains idle after tab changes, and allows a new search', async ({ page }) => {
  await openProgram(page)
  await expect(page.getByText('Không tìm thấy bài tập phù hợp.')).toBeVisible()
  await page.waitForTimeout(700)
  expect(await calls(page)).toHaveLength(1)
  await page.getByRole('button', { name: 'Ca tập', exact: true }).click()
  await page.getByRole('button', { name: 'Giáo án', exact: true }).click()
  await page.waitForTimeout(350)
  expect(await calls(page)).toHaveLength(1)
  await page.getByPlaceholder('Tìm bài tập…').fill('squat')
  await expect.poll(async () => (await calls(page)).length).toBe(2)
  await page.waitForTimeout(700)
  expect(await calls(page)).toEqual([{ query: '', cursor: null, pageSize: 36 }, { query: 'squat', cursor: null, pageSize: 36 }])
})

test('catalog failure does not retry itself; explicit retry submits one request', async ({ page }) => {
  await page.addInitScript(() => { (window as unknown as { catalogFails: boolean }).catalogFails = true })
  await openProgram(page)
  await expect(page.getByRole('alert')).toContainText('Dịch vụ thư viện tạm thời chưa phản hồi.')
  await page.waitForTimeout(700)
  expect(await calls(page)).toHaveLength(1)
  await page.evaluate(() => { (window as unknown as { catalogFails: boolean }).catalogFails = false })
  await page.getByRole('button', { name: 'Thử tải lại thư viện' }).click()
  await expect(page.getByText('Không tìm thấy bài tập phù hợp.')).toBeVisible()
  await page.waitForTimeout(700)
  expect(await calls(page)).toHaveLength(2)
  await expect(page.getByRole('alert')).toHaveCount(0)
})

test('catalog manager debounces typing and ignores older search responses', async ({ page }) => {
  await page.addInitScript(() => {
    Object.assign(window, { catalogItems: true, catalogDelays: { old: 1000 } })
  })
  await page.goto('/tests/workout-catalog-ui/index.html?manager')
  const search = page.getByRole('textbox', { name: 'Tìm trong thư viện bài tập' })
  await expect.poll(async () => (await calls(page)).length).toBe(1)
  await search.pressSequentially('old', { delay: 50 })
  await expect.poll(async () => (await calls(page)).length).toBe(2)
  await search.fill('new')
  await expect(page.locator('.exercise-catalog-manager__list')).toContainText('Bài tập new')
  await page.waitForTimeout(1100)
  expect((await calls(page)).map((call) => call.query)).toEqual(['', 'old', 'new'])
  await expect(page.locator('.exercise-catalog-manager__list')).toContainText('Bài tập new')
  await expect(page.locator('.exercise-catalog-manager__list')).not.toContainText('Bài tập old')
})

test('failed autosave is bounded until another edit or explicit save', async ({ page }) => {
  await page.addInitScript(() => { Object.assign(window, { catalogItems: true, saveFails: true }) })
  await page.goto('/tests/workout-catalog-ui/index.html?manager')
  await page.locator('.exercise-catalog-manager__list button').first().click()
  const name = page.getByPlaceholder('Ví dụ: Đẩy hông với tạ đòn')
  await name.fill('Bài tập đã sửa')
  const saveCalls = () => page.evaluate(() => (window as unknown as { saveCalls: unknown[] }).saveCalls.length)
  await expect.poll(saveCalls).toBe(1)
  await expect(page.getByText('Chưa thể lưu bản nháp.', { exact: true })).toBeVisible()
  await page.waitForTimeout(2300)
  expect(await saveCalls()).toBe(1)
  await name.fill('Bài tập sửa lần hai')
  await expect.poll(saveCalls).toBe(2)
  await page.waitForTimeout(2300)
  expect(await saveCalls()).toBe(2)
  await page.evaluate(() => { (window as unknown as { saveFails: boolean }).saveFails = false })
  await page.getByRole('button', { name: 'Lưu nháp', exact: true }).click()
  await expect(page.getByText('Đã lưu bản nháp bài tập.')).toBeVisible()
  expect(await saveCalls()).toBe(3)
})

test('autosave response preserves edits typed while the write was in flight', async ({ page }) => {
  await page.addInitScript(() => { Object.assign(window, { catalogItems: true, saveDelayMs: 600 }) })
  await page.goto('/tests/workout-catalog-ui/index.html?manager')
  await page.locator('.exercise-catalog-manager__list button').first().click()
  const name = page.getByPlaceholder('Ví dụ: Đẩy hông với tạ đòn')
  await name.fill('Bản trước')
  await expect.poll(() => page.evaluate(() => (window as unknown as { saveCalls: unknown[] }).saveCalls.length)).toBe(1)
  await name.fill('Bản mới giữ lại')
  await expect(page.getByRole('button', { name: 'Lưu nháp', exact: true })).toBeDisabled()
  await page.waitForTimeout(800)
  await expect(name).toHaveValue('Bản mới giữ lại')
  await expect.poll(() => page.evaluate(() => (window as unknown as { saveCalls: unknown[] }).saveCalls.length)).toBe(2)
  await expect(name).toHaveValue('Bản mới giữ lại')
})

test('old autosave cannot overwrite a new editor with the same change version', async ({ page }, testInfo) => {
  await page.addInitScript(() => { Object.assign(window, { catalogItems: true, saveDelayMs: 900 }) })
  await page.goto('/tests/workout-catalog-ui/index.html?manager')
  await page.locator('.exercise-catalog-manager__list button').first().click()
  await page.getByPlaceholder('Ví dụ: Đẩy hông với tạ đòn').fill('Nội dung của bài cũ')
  await expect.poll(() => page.evaluate(() => (window as unknown as { saveCalls: unknown[] }).saveCalls.length)).toBe(1)
  if (testInfo.project.name.includes('mobile')) await page.getByRole('button', { name: 'Danh sách bài tập' }).click()
  await page.getByRole('button', { name: 'Thêm bài tập', exact: true }).click()
  await page.waitForTimeout(1100)
  await expect(page.getByPlaceholder('Ví dụ: Đẩy hông với tạ đòn')).toHaveValue('')
  await expect(page.getByPlaceholder('Barbell Hip Thrust')).toHaveValue('')
  expect(await page.evaluate(() => (window as unknown as { saveCalls: unknown[] }).saveCalls.length)).toBe(1)
})

test('manual save events in the same tick share one write lock', async ({ page }) => {
  await page.addInitScript(() => { Object.assign(window, { catalogItems: true, saveDelayMs: 500 }) })
  await page.goto('/tests/workout-catalog-ui/index.html?manager')
  await page.locator('.exercise-catalog-manager__list button').first().click()
  await page.getByPlaceholder('Ví dụ: Đẩy hông với tạ đòn').fill('Lưu một lần')
  await page.getByRole('button', { name: 'Lưu nháp', exact: true }).evaluate((button) => {
    const save = button as HTMLButtonElement
    save.click()
    save.click()
  })
  await expect(page.getByText('Đã lưu bản nháp bài tập.')).toBeVisible()
  await page.waitForTimeout(2100)
  expect(await page.evaluate(() => (window as unknown as { saveCalls: unknown[] }).saveCalls.length)).toBe(1)
})
