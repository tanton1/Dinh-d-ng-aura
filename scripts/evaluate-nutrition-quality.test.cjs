const { test } = require('node:test')
const assert = require('node:assert/strict')
const { evaluate } = require('./evaluate-nutrition-quality.cjs')
const reference = ['case1', 'case2', 'case3'].map(caseId => ({ caseId, calories: 500, grams: 300, reviewed: true, reviewedAt: '2026-10-30', reviewer: 'private-name', photo: 'private-image' }))
test('quality evaluation separates failures and absent predictions from accuracy', () => {
  const report = evaluate(reference, [{ caseId: 'case1', status: 'completed', calories: 550, grams: 280, needsReview: true, costUsd: .02, durationMs: 1000 }, { caseId: 'case2', status: 'failed', durationMs: 2000 }])
  assert.equal(report.completionRate, .5)
  assert.equal(report.missingPredictions, 1)
  assert.equal(report.meanAbsoluteError.calories, 50)
  assert.equal(report.costUsd.perSuccessfulResult, null)
  assert.equal(report.durationMs.p95, 2000)
  assert.doesNotMatch(JSON.stringify(report), /private-name|private-image/)
})
test('empty benchmark stays unknown; duplicates and unreviewed labels are rejected', () => {
  assert.equal(evaluate([], []).completionRate, null)
  assert.throws(() => evaluate([{ ...reference[0], reviewed: false }], []), /human review/)
  assert.throws(() => evaluate([reference[0], reference[0]], []), /unique/)
  assert.throws(() => evaluate(reference, [{ caseId: 'unknown' }]), /match reference/)
})
