'use strict'

// Reproducible generated artifacts. Authoring code and checkpoint keys must never
// enter a browser entry point, including the admin editor's public JS chunks.
const { buildSync } = require('esbuild')
const { readFileSync, writeFileSync, mkdirSync } = require('node:fs')
const { resolve, dirname } = require('node:path')
const { runInNewContext } = require('node:vm')

const root = resolve(__dirname, '..')
const build = buildSync({
  absWorkingDir: root, entryPoints: ['src/course-template.ts'], bundle: true,
  platform: 'node', format: 'cjs', target: 'node22', write: false, sourcemap: false,
  banner: { js: '// Generated by scripts/build-academy-runtime-assets.cjs. Authoring only; never serve to browsers.' },
})
const serverCode = build.outputFiles[0].text
const context = { module: { exports: {} }, exports: {} }
runInNewContext(serverCode, context)
const course = context.module.exports.auraFoundationCourse
if (course?.modules?.length !== 20) throw new Error('Expected the canonical 20-chapter template.')

const chapterBuild = buildSync({
  absWorkingDir: root, entryPoints: ['src/data/auraNutritionCurriculum.ts'], bundle: true,
  platform: 'node', format: 'cjs', target: 'node22', write: false,
})
const chapterContext = { module: { exports: {} }, exports: {} }
runInNewContext(chapterBuild.outputFiles[0].text, chapterContext)
const chapters = Array.from({ length: 20 }, (_, index) => {
  const { quiz: _authorOnlyQuiz, ...publicChapter } = chapterContext.module.exports.getAuraNutritionChapter(index + 1)
  return publicChapter
})
const outputs = new Map([
  ['functions/generated/academy-course-template.cjs', serverCode],
  ['src/data/generated/auraNutritionLearnerChapters.json', JSON.stringify(chapters, null, 2) + '\n'],
])
const draftBuild = buildSync({
  absWorkingDir: root, entryPoints: ['content/academy/learning-drafts.ts'], bundle: true,
  platform: 'node', format: 'cjs', target: 'node22', write: false, sourcemap: false,
  banner: { js: '// Generated Academy drafts. Staff preview only; not published curriculum.' },
})
outputs.set('functions/generated/academy-learning-drafts.cjs', draftBuild.outputFiles[0].text)
const catalogBuild = buildSync({
  absWorkingDir: root, entryPoints: ['src/features/academy/draftCatalog.ts'], bundle: true,
  platform: 'node', format: 'cjs', target: 'node22', write: false, sourcemap: false,
  banner: { js: '// Generated draft catalog. Chapter metadata only; no lesson content or answer keys.' },
})
outputs.set('functions/generated/academy-draft-catalog.cjs', catalogBuild.outputFiles[0].text)
const checkpointBuild = buildSync({
  absWorkingDir: root, entryPoints: ['content/academy/pilot-checkpoints.ts'], bundle: true,
  platform: 'node', format: 'cjs', target: 'node22', write: false, sourcemap: false,
  banner: { js: '// Generated private pilot checkpoint bank. Never serve to learners or browser bundles.' },
})
outputs.set('functions/generated/academy-pilot-checkpoints.cjs', checkpointBuild.outputFiles[0].text)
const learningCheckpointBuild = buildSync({
  absWorkingDir: root, entryPoints: ['content/academy/learning-checkpoints.ts'], bundle: true,
  platform: 'node', format: 'cjs', target: 'node22', write: false, sourcemap: false,
  banner: { js: '// Generated private draft checkpoint bank. Reviewed version required before adoption; never serve to browsers.' },
})
outputs.set('functions/generated/academy-learning-checkpoints.cjs', learningCheckpointBuild.outputFiles[0].text)
const submissionPolicyBuild = buildSync({
  absWorkingDir: root, entryPoints: ['src/features/academy/submissionPolicy.ts'], bundle: true,
  platform: 'node', format: 'cjs', target: 'node22', write: false, sourcemap: false,
  banner: { js: '// Generated canonical portfolio fields and educational review rubric.' },
})
outputs.set('functions/generated/academy-submission-policy.cjs', submissionPolicyBuild.outputFiles[0].text)
if (process.argv.includes('--write')) {
  for (const [file, content] of outputs) {
    const target = resolve(root, file)
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, content, 'utf8')
    process.stdout.write(`Generated ${file}\n`)
  }
} else {
  for (const [file, content] of outputs) {
    let actual
    try { actual = readFileSync(resolve(root, file), 'utf8').replace(/\r\n/g, '\n') } catch { throw new Error(`Missing generated asset ${file}; run with --write.`) }
    if (actual !== content) throw new Error(`Stale generated asset ${file}; run with --write.`)
  }
  process.stdout.write('Academy runtime artifacts match authoring sources.\n')
}
